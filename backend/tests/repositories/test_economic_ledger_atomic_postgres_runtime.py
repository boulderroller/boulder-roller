def _bootstrap(cursor) -> None:
    cursor.execute(
        """
        CREATE EXTENSION IF NOT EXISTS pgcrypto;
        DO $$ BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
        DO $$ BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
        DO $$ BEGIN CREATE ROLE service_role NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
        CREATE TABLE public.pipeline_versions (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
        );
        INSERT INTO public.pipeline_versions (id) VALUES (7);
        CREATE TABLE public.economic_events (
            id BIGSERIAL PRIMARY KEY,
            event_uuid UUID NOT NULL DEFAULT gen_random_uuid(),
            event_type TEXT NOT NULL,
            wallet TEXT NOT NULL,
            counterparty TEXT,
            amount NUMERIC NOT NULL,
            denomination TEXT NOT NULL DEFAULT 'POINTS',
            balance_after NUMERIC NOT NULL,
            caused_by_id BIGINT REFERENCES public.economic_events(id),
            batch_id UUID,
            pipeline_version_id INTEGER REFERENCES public.pipeline_versions(id),
            reference_type TEXT,
            reference_id TEXT,
            valid_at TIMESTAMPTZ NOT NULL,
            recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            reversal_of_id BIGINT REFERENCES public.economic_events(id),
            is_reversed BOOLEAN NOT NULL DEFAULT FALSE,
            evidence JSONB,
            prev_hash CHAR(64),
            event_hash CHAR(64) NOT NULL
        );
        INSERT INTO public.economic_events (
            event_type, wallet, amount, denomination, balance_after,
            pipeline_version_id, valid_at, event_hash
        ) VALUES (
            'LEGACY', 'legacy-wallet', 1.25, 'CAL', 1.25,
            NULL, '2026-07-01T12:00:00Z', repeat('a', 64)
        );
        CREATE OR REPLACE FUNCTION public.prevent_ledger_mutation()
        RETURNS TRIGGER LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'DELETE' THEN
                RAISE EXCEPTION 'DELETE on economic_events is forbidden. Ledger is append-only.';
            END IF;
            IF NEW.is_reversed = TRUE AND OLD.is_reversed = FALSE
               AND NEW.amount = OLD.amount
               AND NEW.balance_after = OLD.balance_after
               AND NEW.event_hash = OLD.event_hash THEN
                RETURN NEW;
            END IF;
            RAISE EXCEPTION 'UPDATE on economic_events is forbidden';
        END;
        $$;
        CREATE TRIGGER trg_ledger_immutable
            BEFORE UPDATE OR DELETE ON public.economic_events
            FOR EACH ROW EXECUTE FUNCTION public.prevent_ledger_mutation();
        GRANT ALL ON public.economic_events TO anon, authenticated, service_role;
        GRANT ALL ON SEQUENCE public.economic_events_id_seq TO anon, authenticated, service_role;
        """
    )


def _append(
    cursor,
    *,
    wallet: str,
    amount: str,
    valid_at: str = "2026-07-14T16:30:00.123456Z",
) -> tuple:
    cursor.execute(
        """
        SELECT id, amount, balance_after, valid_at, prev_hash, event_hash, hash_version
        FROM public.append_economic_event(
            p_wallet => %s,
            p_event_type => 'TEST_CREDIT',
            p_amount => %s,
            p_denomination => 'CAL',
            p_valid_at => %s,
            p_pipeline_version_id => 7,
            p_reference_type => 'test',
            p_reference_id => %s,
            p_evidence => %s
        )
        """,
        (wallet, amount, valid_at, f"event-{amount}", Json({"amount": amount})),
    )
    return cursor.fetchone()


def test_atomic_append_preserves_legacy_rows_exact_values_and_privileges(
    postgres_dsn: str,
) -> None:
    with _connection(postgres_dsn) as connection:
        with connection.cursor() as cursor:
            _bootstrap(cursor)
            cursor.execute(ATOMIC_LEDGER_SQL)
            cursor.execute(ATOMIC_LEDGER_SQL)

            cursor.execute(
                """
                SELECT pipeline_version_id, event_hash, hash_version
                FROM public.economic_events WHERE wallet = 'legacy-wallet'
                """
            )
            assert cursor.fetchone() == (None, "a" * 64, 1)

            cursor.execute(
                """
                SELECT relrowsecurity
                FROM pg_class
                WHERE oid = 'public.economic_events'::regclass
                """
            )
            assert cursor.fetchone() == (True,)
            cursor.execute(
                """
                SELECT
                    has_table_privilege('service_role', 'public.economic_events', 'SELECT'),
                    has_table_privilege('service_role', 'public.economic_events', 'INSERT'),
                    has_function_privilege(
                        'service_role',
                        'public.append_economic_event(text,text,text,text,timestamptz,integer,bigint,uuid,text,text,text,bigint,jsonb)',
                        'EXECUTE'
                    ),
                    has_function_privilege(
                        'authenticated',
                        'public.append_economic_event(text,text,text,text,timestamptz,integer,bigint,uuid,text,text,text,bigint,jsonb)',
                        'EXECUTE'
                    )
                """
            )
            assert cursor.fetchone() == (True, False, True, False)

            cursor.execute("SET ROLE authenticated")
            with pytest.raises(psycopg2.errors.InsufficientPrivilege):
                _append(cursor, wallet="blocked-wallet", amount="1")
            cursor.execute("RESET ROLE")

            cursor.execute("SET ROLE service_role")
            with pytest.raises(psycopg2.errors.InsufficientPrivilege):
                cursor.execute(
                    """
                    INSERT INTO public.economic_events (
                        event_type, wallet, amount, denomination, balance_after,
                        pipeline_version_id, valid_at, event_hash
                    ) VALUES ('DIRECT', 'blocked', 1, 'CAL', 1, 7, now(), %s)
                    """,
                    ("b" * 64,),
                )
            exact = _append(
                cursor,
                wallet="exact-wallet",
                amount="9007199254740993.000000001",
            )
            dust = _append(cursor, wallet="exact-wallet", amount="0.000000009")
            cursor.execute("RESET ROLE")

            assert exact[1:3] == (
                Decimal("9007199254740993.000000001"),
                Decimal("9007199254740993.000000001"),
            )
            assert dust[1:3] == (
                Decimal("0.000000009"),
                Decimal("9007199254740993.000000010"),
            )
            assert dust[4] == exact[5]
            assert exact[6] == dust[6] == 2

            expected_hash = compute_event_hash_v2(
                wallet="exact-wallet",
                event_type="TEST_CREDIT",
                denomination="CAL",
                amount=exact[1],
                balance_after=exact[2],
                valid_at=exact[3],
                prev_hash=exact[4],
            )
            assert exact[5] == expected_hash

            _append(cursor, wallet="overflow-wallet", amount="9" * 128)
            with pytest.raises(
                psycopg2.errors.RaiseException,
                match="balance_after exceeds",
            ):
                _append(cursor, wallet="overflow-wallet", amount="1")

            with pytest.raises(psycopg2.errors.RaiseException, match="pipeline_version_id"):
                cursor.execute(
                    """
                    SELECT id FROM public.append_economic_event(
                        'missing-pipeline', 'TEST', '1', 'CAL', now(), NULL
                    )
                    """
                )
            with pytest.raises(psycopg2.errors.RaiseException, match="UPDATE on economic_events"):
                cursor.execute(
                    "UPDATE public.economic_events SET amount = 2 WHERE id = %s",
                    (exact[0],),
                )


def test_atomic_append_serializes_concurrent_wallet_stream(
    postgres_dsn: str,
) -> None:
    worker_count = 8
    barrier = Barrier(worker_count)

    def append_one(index: int) -> tuple:
        with _connection(postgres_dsn) as connection:
            with connection.cursor() as cursor:
                cursor.execute("SET ROLE service_role")
                barrier.wait(timeout=10)
                return _append(
                    cursor,
                    wallet="concurrent-wallet",
                    amount="1",
                    valid_at=f"2026-07-14T16:30:{index:02d}Z",
                )

    with ThreadPoolExecutor(max_workers=worker_count) as executor:
        rows = list(executor.map(append_one, range(worker_count)))

    assert len({row[0] for row in rows}) == worker_count
    with _connection(postgres_dsn) as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT id, balance_after, prev_hash, event_hash
                FROM public.economic_events
                WHERE wallet = 'concurrent-wallet' AND denomination = 'CAL'
                ORDER BY id
                """
            )
            persisted = cursor.fetchall()

    assert [row[1] for row in persisted] == [Decimal(i) for i in range(1, 9)]
    assert persisted[0][2] is None
    for previous, current in zip(persisted, persisted[1:]):
        assert current[2] == previous[3]
