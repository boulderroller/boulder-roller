CREATE OR REPLACE FUNCTION public.get_ride_economic_plan(p_ride_id UUID)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT CASE WHEN p.ride_id IS NULL THEN NULL ELSE
        (to_jsonb(p) - 'ride_hash' - 'attestation_commitment' - 'plan_evidence_hash')
        || jsonb_build_object(
            'ride_hash_hex', encode(p.ride_hash, 'hex'),
            'attestation_commitment_hex', encode(p.attestation_commitment, 'hex'),
            'plan_evidence_hash_hex', encode(p.plan_evidence_hash, 'hex'),
            'steps', COALESCE((
                SELECT jsonb_agg(
                    (to_jsonb(s) - 'completion_evidence_hash')
                    || jsonb_build_object(
                        'completion_evidence_hash_hex',
                        encode(s.completion_evidence_hash, 'hex')
                    )
                    ORDER BY s.step_index
                )
                FROM public.ride_economic_completion_steps s
                WHERE s.ride_id = p.ride_id
            ), '[]'::jsonb)
        ) END
    FROM (SELECT 1) anchor
    LEFT JOIN public.ride_economic_plans p ON p.ride_id = p_ride_id;
$$;

CREATE OR REPLACE FUNCTION public.require_ride_economic_uint(
    p_value JSONB,
    p_field TEXT,
    p_maximum NUMERIC
) RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_text TEXT;
    v_value NUMERIC;
BEGIN
    v_text := p_value #>> '{}';
    IF v_text IS NULL OR v_text !~ '^[0-9]+$' THEN
        RAISE EXCEPTION
            'ride economic integer field must contain unsigned decimal digits: %',
            p_field;
    END IF;
    v_value := v_text::NUMERIC;
    IF v_value > p_maximum THEN
        RAISE EXCEPTION 'ride economic integer field exceeds protocol maximum: %',
            p_field;
    END IF;
    RETURN v_value;
END;
$$;

CREATE OR REPLACE FUNCTION public.freeze_ride_economic_plan(
    p_plan JSONB,
    p_steps JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_ride_id UUID := (p_plan->>'ride_id')::UUID;
    v_existing public.ride_economic_plans%ROWTYPE;
    v_step JSONB;
    v_tribute_sum NUMERIC(39, 0) := 0;
BEGIN
    IF jsonb_typeof(p_steps) <> 'array' THEN
        RAISE EXCEPTION 'ride economic completion steps must be an array';
    END IF;

    SELECT * INTO v_existing
    FROM public.ride_economic_plans
    WHERE ride_id = v_ride_id
    FOR UPDATE;

    IF FOUND THEN
        IF encode(v_existing.plan_evidence_hash, 'hex')
            <> lower(p_plan->>'plan_evidence_hash_hex') THEN
            INSERT INTO public.ride_economic_plan_audits (
                ride_id, event_type, state_at_observation,
                frozen_evidence_hash, observed_evidence_hash, details
            ) VALUES (
                v_ride_id,
                CASE WHEN v_existing.state = 'complete'
                    THEN 'completed_plan_evidence_mismatch'
                    ELSE 'nonterminal_plan_evidence_mismatch'
                END,
                v_existing.state,
                v_existing.plan_evidence_hash,
                decode(lower(p_plan->>'plan_evidence_hash_hex'), 'hex'),
                jsonb_build_object(
                    'reason', 'replay supplied a different frozen economic plan'
                )
            ) ON CONFLICT DO NOTHING;

            IF v_existing.state <> 'complete' THEN
                UPDATE public.ride_economic_plans
                SET state = 'review',
                    review_reason = 'frozen_plan_evidence_mismatch',
                    last_error = 'replay supplied a different frozen economic plan',
                    lease_owner = NULL,
                    lease_expires_at = NULL,
                    lock_version = lock_version + 1,
                    updated_at = now()
                WHERE ride_id = v_ride_id;
            END IF;
        END IF;
        RETURN public.get_ride_economic_plan(v_ride_id);
    END IF;

    INSERT INTO public.ride_economic_plans (
        ride_id, user_id, wallet, ride_hash, attestation_commitment,
        parser_version, policy_version, reward_policy, source_kind,
        started_at, completed_at, total_tss, total_distance_m, total_vert_m,
        exact_cal_base_units, climbs_crossed, exact_tribute_base_units,
        plan_evidence_hash, expected_attestation_pda, expected_cal_receipt_pda
    ) VALUES (
        v_ride_id,
        (p_plan->>'user_id')::UUID,
        p_plan->>'wallet',
        decode(p_plan->>'ride_hash_hex', 'hex'),
        decode(p_plan->>'attestation_commitment_hex', 'hex'),
        public.require_ride_economic_uint(
            p_plan->'parser_version', 'parser_version', 4294967295
        )::BIGINT,
        p_plan->>'policy_version',
        p_plan->>'reward_policy',
        public.require_ride_economic_uint(
            p_plan->'source_kind', 'source_kind', 255
        )::SMALLINT,
        (p_plan->>'started_at')::TIMESTAMPTZ,
        (p_plan->>'completed_at')::TIMESTAMPTZ,
        public.require_ride_economic_uint(
            p_plan->'total_tss', 'total_tss', 4294967295
        )::BIGINT,
        public.require_ride_economic_uint(
            p_plan->'total_distance_m', 'total_distance_m', 4294967295
        )::BIGINT,
        public.require_ride_economic_uint(
            p_plan->'total_vert_m', 'total_vert_m', 4294967295
        )::BIGINT,
        public.require_ride_economic_uint(
            p_plan->'exact_cal_base_units',
            'exact_cal_base_units',
            18446744073709551615
        ),
        public.require_ride_economic_uint(
            p_plan->'climbs_crossed', 'climbs_crossed', 65535
        )::INTEGER,
        public.require_ride_economic_uint(
            p_plan->'exact_tribute_base_units',
            'exact_tribute_base_units',
            340282366920938463463374607431768211455
        ),
        decode(p_plan->>'plan_evidence_hash_hex', 'hex'),
        p_plan->>'expected_attestation_pda',
        p_plan->>'expected_cal_receipt_pda'
    );

    FOR v_step IN SELECT value FROM jsonb_array_elements(p_steps)
    LOOP
        v_tribute_sum := v_tribute_sum
            + public.require_ride_economic_uint(
                v_step->'exact_tribute_base_units',
                'exact_tribute_base_units',
                18446744073709551615
            );
        INSERT INTO public.ride_economic_completion_steps (
            ride_id, step_index, pattern_id, vault_id, vault_signature,
            completion_time_s, completed_at, exact_tribute_base_units,
            intensity_bps, climb_distance_m, climb_vert_m,
            completion_evidence_hash, expected_receipt_pda
        ) VALUES (
            v_ride_id,
            public.require_ride_economic_uint(
                v_step->'step_index', 'step_index', 2147483647
            )::INTEGER,
            (v_step->>'pattern_id')::UUID,
            public.require_ride_economic_uint(
                v_step->'vault_id', 'vault_id', 18446744073709551615
            ),
            v_step->>'vault_signature',
            public.require_ride_economic_uint(
                v_step->'completion_time_s', 'completion_time_s', 4294967295
            )::BIGINT,
            (v_step->>'completed_at')::TIMESTAMPTZ,
            public.require_ride_economic_uint(
                v_step->'exact_tribute_base_units',
                'exact_tribute_base_units',
                18446744073709551615
            ),
            public.require_ride_economic_uint(
                v_step->'intensity_bps', 'intensity_bps', 20000
            )::INTEGER,
            CASE
                WHEN v_step->'climb_distance_m' IS NULL
                  OR jsonb_typeof(v_step->'climb_distance_m') = 'null' THEN NULL
                ELSE public.require_ride_economic_uint(
                    v_step->'climb_distance_m', 'climb_distance_m', 4294967295
                )::BIGINT
            END,
            CASE
                WHEN v_step->'climb_vert_m' IS NULL
                  OR jsonb_typeof(v_step->'climb_vert_m') = 'null' THEN NULL
                ELSE public.require_ride_economic_uint(
                    v_step->'climb_vert_m', 'climb_vert_m', 4294967295
                )::BIGINT
            END,
            decode(v_step->>'completion_evidence_hash_hex', 'hex'),
            v_step->>'expected_receipt_pda'
        );
    END LOOP;

    IF v_tribute_sum <> public.require_ride_economic_uint(
        p_plan->'exact_tribute_base_units',
        'exact_tribute_base_units',
        340282366920938463463374607431768211455
    ) THEN
        RAISE EXCEPTION 'ride economic tribute total does not match frozen steps';
    END IF;

    RETURN public.get_ride_economic_plan(v_ride_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.acquire_ride_economic_plan(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_lease_seconds INTEGER DEFAULT 300
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.ride_economic_plans
    SET lease_owner = p_lease_owner,
        lease_expires_at = clock_timestamp()
            + make_interval(secs => GREATEST(30, LEAST(p_lease_seconds, 900))),
        attempts = attempts + 1,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND state NOT IN ('complete', 'review')
      AND next_attempt_at <= clock_timestamp()
      AND (
          lease_owner IS NULL
          OR lease_expires_at <= clock_timestamp()
          OR lease_owner = p_lease_owner
      );

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    RETURN public.get_ride_economic_plan(p_ride_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.advance_ride_economic_plan(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_expected_state TEXT,
    p_next_state TEXT,
    p_fields JSONB DEFAULT '{}'::JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_allowed BOOLEAN := (
        (p_expected_state = 'planned' AND p_next_state = 'attestation_confirmed')
        OR (p_expected_state = 'attestation_confirmed' AND p_next_state = 'completions_confirmed')
        OR (p_expected_state = 'completions_confirmed' AND p_next_state = 'cal_confirmed')
        OR (p_expected_state = 'cal_confirmed' AND p_next_state = 'projections_reconciled')
        OR (p_expected_state = 'projections_reconciled' AND p_next_state = 'complete')
    );
BEGIN
    IF NOT v_allowed THEN
        RAISE EXCEPTION 'invalid ride economic transition: % -> %',
            p_expected_state, p_next_state;
    END IF;
    IF COALESCE(p_fields->>'attestation_actual_tx_signature', '') LIKE 'exists:%'
       OR COALESCE(p_fields->>'cal_actual_tx_signature', '') LIKE 'exists:%' THEN
        RAISE EXCEPTION 'exists:<pda> is not a transaction signature';
    END IF;
    IF p_next_state = 'completions_confirmed' AND EXISTS (
        SELECT 1 FROM public.ride_economic_completion_steps s
        WHERE s.ride_id = p_ride_id
          AND s.state NOT IN ('confirmed', 'projected')
    ) THEN
        RAISE EXCEPTION 'cannot confirm ride completions while a step is pending';
    END IF;
    IF p_next_state = 'projections_reconciled' AND EXISTS (
        SELECT 1 FROM public.ride_economic_completion_steps s
        WHERE s.ride_id = p_ride_id
          AND s.state <> 'projected'
    ) THEN
        RAISE EXCEPTION 'cannot reconcile ride projections while a step is pending';
    END IF;

    UPDATE public.ride_economic_plans
    SET state = p_next_state,
        attestation_actual_tx_signature = CASE
            WHEN p_next_state = 'attestation_confirmed'
                THEN NULLIF(p_fields->>'attestation_actual_tx_signature', '')
            ELSE attestation_actual_tx_signature END,
        attestation_confirmed_at = CASE
            WHEN p_next_state = 'attestation_confirmed'
                THEN (p_fields->>'attestation_confirmed_at')::TIMESTAMPTZ
            ELSE attestation_confirmed_at END,
        cal_actual_tx_signature = CASE
            WHEN p_next_state = 'cal_confirmed'
                THEN NULLIF(p_fields->>'cal_actual_tx_signature', '')
            ELSE cal_actual_tx_signature END,
        cal_confirmed_at = CASE
            WHEN p_next_state = 'cal_confirmed'
                THEN (p_fields->>'cal_confirmed_at')::TIMESTAMPTZ
            ELSE cal_confirmed_at END,
        last_error = NULL,
        lease_owner = CASE WHEN p_next_state = 'complete' THEN NULL ELSE lease_owner END,
        lease_expires_at = CASE WHEN p_next_state = 'complete' THEN NULL ELSE lease_expires_at END,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND state = p_expected_state
      AND lease_owner = p_lease_owner
      AND lease_expires_at > clock_timestamp();

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    RETURN public.get_ride_economic_plan(p_ride_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.confirm_ride_economic_completion(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_step_index INTEGER,
    p_expected_receipt_pda TEXT,
    p_tx_signature TEXT,
    p_confirmed_at TIMESTAMPTZ
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_step public.ride_economic_completion_steps%ROWTYPE;
BEGIN
    IF COALESCE(p_tx_signature, '') LIKE 'exists:%' THEN
        RAISE EXCEPTION 'exists:<pda> is not a transaction signature';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.ride_economic_plans p
        WHERE p.ride_id = p_ride_id
          AND p.state = 'attestation_confirmed'
          AND p.lease_owner = p_lease_owner
          AND p.lease_expires_at > clock_timestamp()
    ) THEN
        RETURN NULL;
    END IF;

    UPDATE public.ride_economic_completion_steps
    SET state = 'confirmed',
        actual_tx_signature = COALESCE(
            NULLIF(p_tx_signature, ''), actual_tx_signature
        ),
        chain_confirmed_at = COALESCE(chain_confirmed_at, p_confirmed_at),
        attempts = attempts + 1,
        last_error = NULL,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND step_index = p_step_index
      AND expected_receipt_pda = p_expected_receipt_pda
      AND state IN ('planned', 'confirmed')
    RETURNING * INTO v_step;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    RETURN (to_jsonb(v_step) - 'completion_evidence_hash')
        || jsonb_build_object(
            'completion_evidence_hash_hex',
            encode(v_step.completion_evidence_hash, 'hex')
        );
END;
$$;

CREATE OR REPLACE FUNCTION public.checkpoint_ride_economic_retry(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_error TEXT,
    p_step_index INTEGER DEFAULT NULL,
    p_retry_delay_seconds INTEGER DEFAULT 30
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.ride_economic_plans
    SET last_error = left(p_error, 2000),
        next_attempt_at = clock_timestamp()
            + make_interval(secs => GREATEST(1, LEAST(p_retry_delay_seconds, 3600))),
        lease_owner = NULL,
        lease_expires_at = NULL,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND lease_owner = p_lease_owner
      AND state NOT IN ('complete', 'review');
    IF NOT FOUND THEN
        RETURN false;
    END IF;

    IF p_step_index IS NOT NULL THEN
        UPDATE public.ride_economic_completion_steps
        SET attempts = attempts + 1,
            last_error = left(p_error, 2000),
            updated_at = now()
        WHERE ride_id = p_ride_id AND step_index = p_step_index;
    END IF;
    RETURN true;
END;
$$;

