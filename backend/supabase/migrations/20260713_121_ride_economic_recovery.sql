CREATE OR REPLACE VIEW public.confirmed_vault_completion_candidates
WITH (security_invoker = true)
AS
SELECT
    s.vault_id,
    vc.vault_signature,
    vc.wallet,
    vc.activity_id,
    vc.completed_at,
    vc.time_seconds,
    vc.cal_tribute,
    vc.on_chain_tx,
    vc.chain_confirmation_status,
    vc.completion_receipt_pda,
    vc.completion_evidence_hash,
    vc.chain_confirmed_at
FROM public.vault_completions vc
JOIN public.ride_economic_plans p
  ON p.ride_id::TEXT = vc.activity_id
JOIN public.ride_economic_completion_steps s
  ON s.ride_id = p.ride_id
 AND s.vault_signature = vc.vault_signature
 AND s.expected_receipt_pda = vc.completion_receipt_pda
WHERE p.state = 'complete'
  AND s.state = 'projected'
  AND vc.chain_confirmation_status = 'confirmed'
  AND vc.completion_receipt_pda IS NOT NULL
  AND vc.chain_confirmed_at IS NOT NULL
  AND (vc.on_chain_tx IS NULL OR vc.on_chain_tx NOT LIKE 'exists:%');

REVOKE ALL ON public.confirmed_vault_completion_candidates FROM PUBLIC;
REVOKE ALL ON public.confirmed_vault_completion_candidates FROM anon, authenticated;
GRANT SELECT ON public.confirmed_vault_completion_candidates TO service_role;

CREATE OR REPLACE FUNCTION public.get_confirmed_local_legend_candidates(
    p_vault_id NUMERIC,
    p_completed_from TIMESTAMPTZ,
    p_completed_before TIMESTAMPTZ
) RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_candidates JSONB;
    v_confirmed_receipt_count BIGINT;
    v_wallet_count BIGINT;
BEGIN
    IF p_vault_id IS NULL
       OR p_vault_id <> trunc(p_vault_id)
       OR p_vault_id < 0
       OR p_vault_id > 18446744073709551615 THEN
        RAISE EXCEPTION 'p_vault_id must be an unsigned 64-bit integer';
    END IF;
    IF p_completed_from IS NULL
       OR p_completed_before IS NULL
       OR p_completed_from >= p_completed_before THEN
        RAISE EXCEPTION 'Local Legend candidate interval must be non-empty';
    END IF;

    WITH grouped AS (
        SELECT
            c.wallet,
            count(*)::BIGINT AS completion_count,
            min(c.completed_at) AS first_completed_at
        FROM public.confirmed_vault_completion_candidates c
        WHERE c.vault_id = p_vault_id
          AND c.completed_at >= p_completed_from
          AND c.completed_at < p_completed_before
        GROUP BY c.wallet
    )
    SELECT
        COALESCE(
            jsonb_agg(
                jsonb_build_object(
                    'wallet', grouped.wallet,
                    'completion_count', grouped.completion_count,
                    'first_completed_at', grouped.first_completed_at
                )
                ORDER BY
                    grouped.completion_count DESC,
                    grouped.first_completed_at,
                    grouped.wallet
            ),
            '[]'::JSONB
        ),
        COALESCE(sum(grouped.completion_count), 0)::BIGINT,
        count(*)::BIGINT
    INTO v_candidates, v_confirmed_receipt_count, v_wallet_count
    FROM grouped;

    RETURN jsonb_build_object(
        'authoritative', true,
        'confirmed_receipt_count', v_confirmed_receipt_count,
        'wallet_count', v_wallet_count,
        'candidates', v_candidates
    );
END;
$$;

