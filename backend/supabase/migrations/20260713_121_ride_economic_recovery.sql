-- Durable, replay-safe ride economic execution.
--
-- A frozen plan is the database checkpoint for one ride's attestation,
-- per-climb completion receipts, CAL credit, and downstream projections.

CREATE TABLE IF NOT EXISTS public.ride_economic_plans (
    -- Frozen identity remains after rider/ride deletion so chain recovery and
    -- receipt evidence cannot be erased by mutable product-data ownership.
    ride_id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    wallet TEXT NOT NULL,
    ride_hash BYTEA NOT NULL CHECK (octet_length(ride_hash) = 32),
    attestation_commitment BYTEA NOT NULL
        CHECK (octet_length(attestation_commitment) = 32),
    parser_version BIGINT NOT NULL
        CHECK (parser_version >= 0 AND parser_version <= 4294967295),
    policy_version TEXT NOT NULL,
    reward_policy TEXT NOT NULL,
    source_kind SMALLINT NOT NULL CHECK (source_kind BETWEEN 0 AND 255),
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    total_tss BIGINT NOT NULL CHECK (total_tss >= 0 AND total_tss <= 4294967295),
    total_distance_m BIGINT NOT NULL
        CHECK (total_distance_m >= 0 AND total_distance_m <= 4294967295),
    total_vert_m BIGINT NOT NULL
        CHECK (total_vert_m >= 0 AND total_vert_m <= 4294967295),
    exact_cal_base_units NUMERIC(20, 0) NOT NULL
        CHECK (
            exact_cal_base_units >= 0
            AND exact_cal_base_units <= 18446744073709551615
        ),
    climbs_crossed INTEGER NOT NULL
        CHECK (climbs_crossed >= 0 AND climbs_crossed <= 65535),
    exact_tribute_base_units NUMERIC(39, 0) NOT NULL CHECK (
        exact_tribute_base_units >= 0 AND exact_tribute_base_units <= 340282366920938463463374607431768211455
    ),
    plan_evidence_hash BYTEA NOT NULL UNIQUE
        CHECK (octet_length(plan_evidence_hash) = 32),
    expected_attestation_pda TEXT NOT NULL,
    expected_cal_receipt_pda TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'planned' CHECK (
        state IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed',
            'projections_reconciled',
            'complete',
            'review'
        )
    ),
    attestation_actual_tx_signature TEXT,
    attestation_confirmed_at TIMESTAMPTZ,
    cal_actual_tx_signature TEXT,
    cal_confirmed_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_owner UUID,
    lease_expires_at TIMESTAMPTZ,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT,
    review_reason TEXT,
    terminal_projection_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (terminal_projection_attempts >= 0),
    terminal_projection_error TEXT,
    terminal_projected_at TIMESTAMPTZ,
    lock_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        attestation_actual_tx_signature IS NULL
        OR attestation_actual_tx_signature NOT LIKE 'exists:%'
    ),
    CHECK (
        cal_actual_tx_signature IS NULL
        OR cal_actual_tx_signature NOT LIKE 'exists:%'
    ),
    CHECK (
        state IN ('planned', 'review')
        OR attestation_confirmed_at IS NOT NULL
    ),
    CHECK (
        state NOT IN ('cal_confirmed', 'projections_reconciled', 'complete')
        OR cal_confirmed_at IS NOT NULL
    ),
    CHECK (
        (lease_owner IS NULL AND lease_expires_at IS NULL)
        OR (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)
    ),
    CHECK (completed_at >= started_at)
);

CREATE TABLE IF NOT EXISTS public.ride_economic_completion_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id UUID NOT NULL REFERENCES public.ride_economic_plans(ride_id)
        ON DELETE CASCADE,
    step_index INTEGER NOT NULL CHECK (step_index >= 0),
    pattern_id UUID NOT NULL,
    vault_id NUMERIC(20, 0) NOT NULL
        CHECK (vault_id >= 0 AND vault_id <= 18446744073709551615),
    vault_signature TEXT NOT NULL,
    completion_time_s BIGINT NOT NULL
        CHECK (completion_time_s >= 1 AND completion_time_s <= 4294967295),
    completed_at TIMESTAMPTZ NOT NULL,
    exact_tribute_base_units NUMERIC(20, 0) NOT NULL
        CHECK (
            exact_tribute_base_units >= 0
            AND exact_tribute_base_units <= 18446744073709551615
        ),
    intensity_bps INTEGER NOT NULL CHECK (intensity_bps BETWEEN 0 AND 20000),
    climb_distance_m BIGINT CHECK (
        climb_distance_m IS NULL OR climb_distance_m BETWEEN 0 AND 4294967295
    ),
    climb_vert_m BIGINT CHECK (
        climb_vert_m IS NULL OR climb_vert_m BETWEEN 0 AND 4294967295
    ),
    completion_evidence_hash BYTEA NOT NULL
        CHECK (octet_length(completion_evidence_hash) = 32),
    expected_receipt_pda TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'planned'
        CHECK (state IN ('planned', 'confirmed', 'projected', 'review')),
    actual_tx_signature TEXT,
    chain_confirmed_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ride_id, step_index),
    UNIQUE (ride_id, vault_id),
    UNIQUE (expected_receipt_pda),
    UNIQUE (completion_evidence_hash),
    CHECK (actual_tx_signature IS NULL OR actual_tx_signature NOT LIKE 'exists:%'),
    CHECK (state IN ('planned', 'review') OR chain_confirmed_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.ride_economic_plan_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id UUID NOT NULL REFERENCES public.ride_economic_plans(ride_id)
        ON DELETE CASCADE,
    event_type TEXT NOT NULL CHECK (
        event_type IN (
            'nonterminal_plan_evidence_mismatch',
            'completed_plan_evidence_mismatch'
        )
    ),
    state_at_observation TEXT NOT NULL,
    frozen_evidence_hash BYTEA NOT NULL
        CHECK (octet_length(frozen_evidence_hash) = 32),
    observed_evidence_hash BYTEA NOT NULL
        CHECK (octet_length(observed_evidence_hash) = 32),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ride_id, event_type, observed_evidence_hash)
);

CREATE INDEX IF NOT EXISTS idx_ride_economic_recovery_due
    ON public.ride_economic_plans(next_attempt_at, created_at)
    WHERE state NOT IN ('complete', 'review');

CREATE INDEX IF NOT EXISTS idx_ride_economic_lease_expiry
    ON public.ride_economic_plans(lease_expires_at)
    WHERE lease_owner IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_ride_economic_terminal_projection_due
    ON public.ride_economic_plans(next_attempt_at, created_at)
