CREATE OR REPLACE FUNCTION public.enforce_vault_completion_chain_authority()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NEW.chain_confirmation_status <> 'confirmed' THEN
        NEW.validated := false;
        NEW.validation_override := false;
        NEW.validation_notes := COALESCE(
            NEW.validation_notes,
            'legacy_unverified: no finalized ride completion receipt'
        );
    END IF;
    RETURN NEW;
END;
$$;

