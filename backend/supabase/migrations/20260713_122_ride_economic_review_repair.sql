CREATE OR REPLACE FUNCTION public.freeze_ride_economic_plan(
    p_plan JSONB,
    p_steps JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_ride_id UUID := (p_plan->>'ride_id')::UUID;
    v_existing public.ride_economic_plans%ROWTYPE;
    v_observed_hash BYTEA;
BEGIN
    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(v_ride_id::TEXT, 0)
    );
    SELECT * INTO v_existing
    FROM public.ride_economic_plans
    WHERE ride_id = v_ride_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN public.freeze_ride_economic_plan_unreviewed(p_plan, p_steps);
    END IF;

    v_observed_hash := decode(
        lower(p_plan->>'plan_evidence_hash_hex'),
        'hex'
    );
    IF v_existing.plan_evidence_hash <> v_observed_hash THEN
        INSERT INTO public.ride_economic_plan_audits (
            ride_id, event_type, state_at_observation,
            frozen_evidence_hash, observed_evidence_hash, details
        ) VALUES (
            v_ride_id,
            CASE WHEN v_existing.state IN ('complete', 'rejected')
                THEN 'completed_plan_evidence_mismatch'
                ELSE 'nonterminal_plan_evidence_mismatch'
            END,
            v_existing.state,
            v_existing.plan_evidence_hash,
            v_observed_hash,
            jsonb_build_object(
                'reason', 'replay supplied a different frozen economic plan'
            )
        ) ON CONFLICT DO NOTHING;

        IF v_existing.state NOT IN ('complete', 'review', 'rejected') THEN
            PERFORM public.enter_ride_economic_review(
                v_ride_id,
                NULL,
                false,
                'frozen_plan_evidence_mismatch',
                'service:freeze_ride_economic_plan',
                jsonb_build_object(
                    'version', 1,
                    'kind', 'frozen_plan_evidence_mismatch',
                    'operation', 'freeze_plan',
                    'message',
                        'replay supplied a different frozen economic plan',
                    'frozen_plan_evidence_hash_hex',
                        encode(v_existing.plan_evidence_hash, 'hex'),
                    'observed_plan_evidence_hash_hex',
                        encode(v_observed_hash, 'hex'),
                    'observed_at', clock_timestamp()
                )
            );
        END IF;
    END IF;
    RETURN public.get_ride_economic_plan(v_ride_id);
END;
$$;

-- Existing review rows predate prior-checkpoint capture. Infer only a lower
-- bound for their legacy checkpoint and require fresh finalized evidence for
-- any resolution; the inference is explicitly marked in the audit record.
UPDATE public.ride_economic_plans
SET review_version = 1
WHERE state = 'review' AND review_version = 0;

INSERT INTO public.ride_economic_reviews (
    ride_id, review_version, prior_state, prior_lock_version,
    frozen_facts, prior_checkpoint, finalized_evidence,
    conflict_evidence, reason, actor
)
SELECT
    p.ride_id,
    p.review_version,
    CASE
        WHEN p.cal_confirmed_at IS NOT NULL THEN 'cal_confirmed'
        WHEN p.attestation_confirmed_at IS NOT NULL
             AND NOT EXISTS (
                SELECT 1
                FROM public.ride_economic_completion_steps s
                WHERE s.ride_id = p.ride_id
                  AND s.chain_confirmed_at IS NULL
             ) THEN 'completions_confirmed'
        WHEN p.attestation_confirmed_at IS NOT NULL
            THEN 'attestation_confirmed'
        ELSE 'planned'
    END,
    p.lock_version,
    public.ride_economic_frozen_facts(p.ride_id),
    public.ride_economic_prior_checkpoint(p.ride_id)
        || jsonb_build_object(
            'legacy_inferred', true,
            'state', CASE
                WHEN p.cal_confirmed_at IS NOT NULL THEN 'cal_confirmed'
                WHEN p.attestation_confirmed_at IS NOT NULL
                     AND NOT EXISTS (
                        SELECT 1
                        FROM public.ride_economic_completion_steps s
                        WHERE s.ride_id = p.ride_id
                          AND s.chain_confirmed_at IS NULL
                     ) THEN 'completions_confirmed'
                WHEN p.attestation_confirmed_at IS NOT NULL
                    THEN 'attestation_confirmed'
                ELSE 'planned'
            END
        ),
    public.ride_economic_known_finalized_evidence(p.ride_id),
    jsonb_build_object(
        'version', 1,
        'kind', 'legacy_review_backfill',
        'operation', 'migration_122',
        'message', 'review existed before durable checkpoint capture',
        'observed_at', clock_timestamp()
    ),
    COALESCE(NULLIF(btrim(p.review_reason), ''), 'legacy_review'),
    'migration:122'
FROM public.ride_economic_plans p
WHERE p.state = 'review'
  AND NOT EXISTS (
      SELECT 1
      FROM public.ride_economic_reviews r
      WHERE r.ride_id = p.ride_id
        AND r.review_version = p.review_version
  );

