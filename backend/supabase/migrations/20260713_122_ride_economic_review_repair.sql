CREATE OR REPLACE FUNCTION public.acquire_ride_economic_plan(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_lease_seconds INTEGER DEFAULT 300
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.ride_economic_plans
    SET lease_owner = p_lease_owner,
        lease_expires_at = clock_timestamp()
            + make_interval(secs => GREATEST(30, LEAST(p_lease_seconds, 900))),
        attempts = attempts + 1,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND state NOT IN ('complete', 'review', 'rejected')
      AND next_attempt_at <= clock_timestamp()
      AND (
          lease_owner IS NULL
          OR lease_expires_at <= clock_timestamp()
          OR lease_owner = p_lease_owner
      );

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    RETURN public.get_ride_economic_plan(p_ride_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.checkpoint_ride_economic_retry(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_error TEXT,
    p_step_index INTEGER DEFAULT NULL,
    p_retry_delay_seconds INTEGER DEFAULT 30
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.ride_economic_plans
    SET last_error = left(p_error, 2000),
        next_attempt_at = clock_timestamp()
            + make_interval(secs => GREATEST(1, LEAST(p_retry_delay_seconds, 3600))),
        lease_owner = NULL,
        lease_expires_at = NULL,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND lease_owner = p_lease_owner
      AND state NOT IN ('complete', 'review', 'rejected');
    IF NOT FOUND THEN
        RETURN false;
    END IF;

    IF p_step_index IS NOT NULL THEN
        UPDATE public.ride_economic_completion_steps
        SET attempts = attempts + 1,
            last_error = left(p_error, 2000),
            updated_at = now()
        WHERE ride_id = p_ride_id AND step_index = p_step_index;
    END IF;
    RETURN true;
END;
$$;

