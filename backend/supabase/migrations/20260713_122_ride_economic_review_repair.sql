-- Repair durable ride-economic review states without weakening frozen plans.
--
-- Review entry snapshots the prior checkpoint and known finalized effects.
-- Resolution requires a complete, finalized chain observation and records one
-- append-only decision per review version before execution may continue.

ALTER TABLE public.ride_economic_plans
    ADD COLUMN IF NOT EXISTS review_version BIGINT NOT NULL DEFAULT 0
        CHECK (review_version >= 0);

ALTER TABLE public.ride_economic_plans
    DROP CONSTRAINT IF EXISTS ride_economic_plans_state_check;
ALTER TABLE public.ride_economic_plans
    ADD CONSTRAINT ride_economic_plans_state_check CHECK (
        state IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed',
            'projections_reconciled',
            'complete',
            'review',
            'rejected'
        )
    );

DO $$
DECLARE
    v_constraint_name TEXT;
BEGIN
    SELECT c.conname INTO v_constraint_name
    FROM pg_catalog.pg_constraint c
    JOIN pg_catalog.pg_class t ON t.oid = c.conrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = 'public'
      AND t.relname = 'ride_economic_plans'
      AND c.contype = 'c'
      AND pg_catalog.pg_get_constraintdef(c.oid)
            LIKE '%attestation_confirmed_at IS NOT NULL%'
    LIMIT 1;
    IF v_constraint_name IS NOT NULL THEN
        EXECUTE format(
            'ALTER TABLE public.ride_economic_plans DROP CONSTRAINT %I',
            v_constraint_name
        );
    END IF;
END;
$$;
ALTER TABLE public.ride_economic_plans
    DROP CONSTRAINT IF EXISTS ride_economic_plans_attestation_checkpoint_check;
ALTER TABLE public.ride_economic_plans
    ADD CONSTRAINT ride_economic_plans_attestation_checkpoint_check CHECK (
        state IN ('planned', 'review', 'rejected')
        OR attestation_confirmed_at IS NOT NULL
    );

CREATE TABLE IF NOT EXISTS public.ride_economic_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id UUID NOT NULL REFERENCES public.ride_economic_plans(ride_id),
    review_version BIGINT NOT NULL CHECK (review_version > 0),
    prior_state TEXT NOT NULL CHECK (
        prior_state IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed',
            'projections_reconciled'
        )
    ),
    prior_lock_version BIGINT NOT NULL CHECK (prior_lock_version >= 0),
    frozen_facts JSONB NOT NULL CHECK (jsonb_typeof(frozen_facts) = 'object'),
    prior_checkpoint JSONB NOT NULL
        CHECK (jsonb_typeof(prior_checkpoint) = 'object'),
    finalized_evidence JSONB NOT NULL
        CHECK (jsonb_typeof(finalized_evidence) = 'object'),
    conflict_evidence JSONB NOT NULL
        CHECK (jsonb_typeof(conflict_evidence) = 'object'),
    reason TEXT NOT NULL CHECK (btrim(reason) <> '' AND length(reason) <= 2000),
    actor TEXT NOT NULL CHECK (btrim(actor) <> '' AND length(actor) <= 200),
    entered_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (ride_id, review_version)
);

CREATE TABLE IF NOT EXISTS public.ride_economic_review_resolutions (
    request_id UUID PRIMARY KEY,
    ride_id UUID NOT NULL REFERENCES public.ride_economic_plans(ride_id),
    review_version BIGINT NOT NULL CHECK (review_version > 0),
    actor_id UUID NOT NULL,
    outcome TEXT NOT NULL
        CHECK (outcome IN ('reconcile', 'resume', 'reject')),
    selected_checkpoint TEXT CHECK (
        selected_checkpoint IS NULL OR selected_checkpoint IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed'
        )
    ),
    verified_checkpoint TEXT NOT NULL CHECK (
        verified_checkpoint IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed'
        )
    ),
    result_state TEXT NOT NULL CHECK (
        result_state IN (
            'planned',
            'attestation_confirmed',
            'completions_confirmed',
            'cal_confirmed',
            'rejected'
        )
    ),
    reason TEXT NOT NULL CHECK (btrim(reason) <> '' AND length(reason) <= 2000),
    chain_evidence JSONB NOT NULL
        CHECK (jsonb_typeof(chain_evidence) = 'object'),
    liability_disposition TEXT,
    effects_disposition TEXT,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (ride_id, review_version)
);

ALTER TABLE public.ride_economic_review_resolutions
    DROP CONSTRAINT IF EXISTS
        ride_economic_review_resolutions_liability_length;
ALTER TABLE public.ride_economic_review_resolutions
    ADD CONSTRAINT ride_economic_review_resolutions_liability_length CHECK (
        liability_disposition IS NULL
        OR length(liability_disposition) <= 2000
    );
ALTER TABLE public.ride_economic_review_resolutions
    DROP CONSTRAINT IF EXISTS
        ride_economic_review_resolutions_effects_length;
ALTER TABLE public.ride_economic_review_resolutions
    ADD CONSTRAINT ride_economic_review_resolutions_effects_length CHECK (
        effects_disposition IS NULL
        OR length(effects_disposition) <= 2000
    );

CREATE INDEX IF NOT EXISTS idx_ride_economic_reviews_ride
    ON public.ride_economic_reviews(ride_id, review_version DESC);
CREATE INDEX IF NOT EXISTS idx_ride_economic_resolutions_actor
    ON public.ride_economic_review_resolutions(actor_id, decided_at DESC);

ALTER TABLE public.ride_economic_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ride_economic_review_resolutions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ride_economic_reviews FROM PUBLIC;
REVOKE ALL ON public.ride_economic_review_resolutions FROM PUBLIC;
REVOKE ALL ON public.ride_economic_reviews FROM anon, authenticated;
REVOKE ALL ON public.ride_economic_review_resolutions FROM anon, authenticated;
REVOKE ALL ON public.ride_economic_reviews FROM service_role;
REVOKE ALL ON public.ride_economic_review_resolutions FROM service_role;
REVOKE ALL ON SEQUENCE public.ride_economic_reviews_id_seq FROM service_role;
GRANT SELECT ON public.ride_economic_reviews TO service_role;
GRANT SELECT ON public.ride_economic_review_resolutions TO service_role;

CREATE OR REPLACE FUNCTION public.ride_economic_frozen_facts(p_ride_id UUID)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT jsonb_build_object(
        'ride_id', p.ride_id,
        'user_id', p.user_id,
        'wallet', p.wallet,
        'ride_hash_hex', encode(p.ride_hash, 'hex'),
        'attestation_commitment_hex', encode(p.attestation_commitment, 'hex'),
        'parser_version', p.parser_version,
        'policy_version', p.policy_version,
        'reward_policy', p.reward_policy,
        'source_kind', p.source_kind,
        'started_at', p.started_at,
        'completed_at', p.completed_at,
        'total_tss', p.total_tss,
        'total_distance_m', p.total_distance_m,
        'total_vert_m', p.total_vert_m,
        'exact_cal_base_units', p.exact_cal_base_units,
        'climbs_crossed', p.climbs_crossed,
        'exact_tribute_base_units', p.exact_tribute_base_units,
        'plan_evidence_hash_hex', encode(p.plan_evidence_hash, 'hex'),
        'expected_attestation_pda', p.expected_attestation_pda,
        'expected_cal_receipt_pda', p.expected_cal_receipt_pda,
        'steps', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'step_index', s.step_index,
                    'pattern_id', s.pattern_id,
                    'vault_id', s.vault_id,
                    'vault_signature', s.vault_signature,
                    'completion_time_s', s.completion_time_s,
                    'completed_at', s.completed_at,
                    'exact_tribute_base_units', s.exact_tribute_base_units,
                    'intensity_bps', s.intensity_bps,
                    'climb_distance_m', s.climb_distance_m,
                    'climb_vert_m', s.climb_vert_m,
                    'completion_evidence_hash_hex',
                        encode(s.completion_evidence_hash, 'hex'),
                    'expected_receipt_pda', s.expected_receipt_pda
                ) ORDER BY s.step_index
            )
            FROM public.ride_economic_completion_steps s
            WHERE s.ride_id = p.ride_id
        ), '[]'::JSONB)
    )
    FROM public.ride_economic_plans p
    WHERE p.ride_id = p_ride_id;
$$;

CREATE OR REPLACE FUNCTION public.ride_economic_prior_checkpoint(p_ride_id UUID)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT jsonb_build_object(
        'state', p.state,
        'lock_version', p.lock_version,
        'attestation_actual_tx_signature', p.attestation_actual_tx_signature,
        'attestation_confirmed_at', p.attestation_confirmed_at,
        'cal_actual_tx_signature', p.cal_actual_tx_signature,
        'cal_confirmed_at', p.cal_confirmed_at,
        'steps', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'step_index', s.step_index,
                    'state', s.state,
                    'actual_tx_signature', s.actual_tx_signature,
                    'chain_confirmed_at', s.chain_confirmed_at,
                    'attempts', s.attempts,
                    'last_error', s.last_error
                ) ORDER BY s.step_index
            )
            FROM public.ride_economic_completion_steps s
            WHERE s.ride_id = p.ride_id
        ), '[]'::JSONB)
    )
    FROM public.ride_economic_plans p
    WHERE p.ride_id = p_ride_id;
$$;

CREATE OR REPLACE FUNCTION public.ride_economic_known_finalized_evidence(
    p_ride_id UUID
) RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT jsonb_build_object(
        'attestation', jsonb_build_object(
            'status', CASE WHEN p.attestation_confirmed_at IS NULL
                THEN 'absent' ELSE 'finalized' END,
            'pda', p.expected_attestation_pda,
            'tx_signature', p.attestation_actual_tx_signature,
            'confirmed_at', p.attestation_confirmed_at
        ),
        'completions', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'step_index', s.step_index,
                    'status', CASE WHEN s.chain_confirmed_at IS NULL
                        THEN 'absent' ELSE 'finalized' END,
                    'pda', s.expected_receipt_pda,
                    'tx_signature', s.actual_tx_signature,
                    'confirmed_at', s.chain_confirmed_at
                ) ORDER BY s.step_index
            )
            FROM public.ride_economic_completion_steps s
            WHERE s.ride_id = p.ride_id
        ), '[]'::JSONB),
        'cal', jsonb_build_object(
            'status', CASE WHEN p.cal_confirmed_at IS NULL
                THEN 'absent' ELSE 'finalized' END,
            'pda', p.expected_cal_receipt_pda,
            'tx_signature', p.cal_actual_tx_signature,
            'confirmed_at', p.cal_confirmed_at
        )
    )
    FROM public.ride_economic_plans p
    WHERE p.ride_id = p_ride_id;
$$;

CREATE OR REPLACE FUNCTION public.enter_ride_economic_review(
    p_ride_id UUID,
    p_lease_owner UUID,
    p_require_lease BOOLEAN,
    p_reason TEXT,
    p_actor TEXT,
    p_conflict_evidence JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_plan public.ride_economic_plans%ROWTYPE;
    v_review_version BIGINT;
    v_observed_at TIMESTAMPTZ;
BEGIN
    IF p_reason IS NULL OR btrim(p_reason) = '' OR length(p_reason) > 2000 THEN
        RAISE EXCEPTION 'ride economic review requires a bounded reason';
    END IF;
    IF p_actor IS NULL OR btrim(p_actor) = '' OR length(p_actor) > 200 THEN
        RAISE EXCEPTION 'ride economic review requires an actor';
    END IF;
    IF jsonb_typeof(p_conflict_evidence) <> 'object'
       OR p_conflict_evidence->>'version' <> '1'
       OR COALESCE(btrim(p_conflict_evidence->>'kind'), '') = ''
       OR COALESCE(btrim(p_conflict_evidence->>'operation'), '') = ''
       OR COALESCE(btrim(p_conflict_evidence->>'message'), '') = '' THEN
        RAISE EXCEPTION 'ride economic review requires structured conflict evidence';
    END IF;
    BEGIN
        v_observed_at := (p_conflict_evidence->>'observed_at')::TIMESTAMPTZ;
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION 'ride economic review conflict evidence requires observed_at';
    END;
    IF v_observed_at IS NULL THEN
        RAISE EXCEPTION 'ride economic review conflict evidence requires observed_at';
    END IF;

    SELECT * INTO v_plan
    FROM public.ride_economic_plans
    WHERE ride_id = p_ride_id
    FOR UPDATE;
    IF NOT FOUND
       OR v_plan.state IN ('complete', 'review', 'rejected')
       OR (
            p_require_lease
            AND (
                v_plan.lease_owner IS DISTINCT FROM p_lease_owner
                OR v_plan.lease_expires_at <= clock_timestamp()
            )
       ) THEN
        RETURN NULL;
    END IF;

    v_review_version := v_plan.review_version + 1;
    INSERT INTO public.ride_economic_reviews (
        ride_id, review_version, prior_state, prior_lock_version,
        frozen_facts, prior_checkpoint, finalized_evidence,
        conflict_evidence, reason, actor
    ) VALUES (
        p_ride_id,
        v_review_version,
        v_plan.state,
        v_plan.lock_version,
        public.ride_economic_frozen_facts(p_ride_id),
        public.ride_economic_prior_checkpoint(p_ride_id),
        public.ride_economic_known_finalized_evidence(p_ride_id),
        p_conflict_evidence,
        btrim(p_reason),
        btrim(p_actor)
    );

    UPDATE public.ride_economic_plans
    SET state = 'review',
        review_version = v_review_version,
        review_reason = btrim(p_reason),
        last_error = btrim(p_reason),
        lease_owner = NULL,
        lease_expires_at = NULL,
        lock_version = lock_version + 1,
        updated_at = now()
    WHERE ride_id = p_ride_id
      AND lock_version = v_plan.lock_version;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ride economic review checkpoint CAS failed';
    END IF;
    RETURN public.get_ride_economic_plan(p_ride_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.resolve_ride_economic_review(
    p_ride_id UUID,
    p_expected_review_version BIGINT,
    p_request_id UUID,
    p_actor_id UUID,
    p_outcome TEXT,
    p_selected_checkpoint TEXT,
    p_reason TEXT,
    p_chain_evidence JSONB,
    p_liability_disposition TEXT,
    p_effects_disposition TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_plan public.ride_economic_plans%ROWTYPE;
    v_review public.ride_economic_reviews%ROWTYPE;
    v_existing public.ride_economic_review_resolutions%ROWTYPE;
    v_resolution public.ride_economic_review_resolutions%ROWTYPE;
    v_validation JSONB;
    v_observation JSONB;
    v_prior_observation JSONB;
    v_attestation JSONB;
    v_cal JSONB;
    v_outcome TEXT := btrim(p_outcome);
    v_selected_checkpoint TEXT := NULLIF(btrim(p_selected_checkpoint), '');
    v_reason TEXT := btrim(p_reason);
    v_liability_disposition TEXT := NULLIF(btrim(p_liability_disposition), '');
    v_effects_disposition TEXT := NULLIF(btrim(p_effects_disposition), '');
    v_verified_checkpoint TEXT;
    v_result_state TEXT;
BEGIN
    IF p_ride_id IS NULL
       OR p_expected_review_version IS NULL
       OR p_expected_review_version <= 0
       OR p_request_id IS NULL
       OR p_actor_id IS NULL THEN
        RAISE EXCEPTION 'ride economic resolution requires exact UUID and review version inputs';
    END IF;
    IF v_outcome IS NULL
       OR v_outcome NOT IN ('reconcile', 'resume', 'reject') THEN
        RAISE EXCEPTION 'ride economic review outcome must be reconcile, resume, or reject';
    END IF;
    IF v_reason IS NULL OR v_reason = '' OR length(v_reason) > 2000 THEN
        RAISE EXCEPTION 'ride economic review resolution requires a bounded reason';
    END IF;
    IF (v_liability_disposition IS NOT NULL
        AND length(v_liability_disposition) > 2000)
       OR (v_effects_disposition IS NOT NULL
           AND length(v_effects_disposition) > 2000) THEN
        RAISE EXCEPTION
            'ride economic review dispositions must be bounded to 2000 characters';
    END IF;

    SELECT * INTO v_existing
    FROM public.ride_economic_review_resolutions
    WHERE request_id = p_request_id;
    IF FOUND THEN
        IF v_existing.ride_id IS DISTINCT FROM p_ride_id
           OR v_existing.review_version IS DISTINCT FROM p_expected_review_version
           OR v_existing.actor_id IS DISTINCT FROM p_actor_id
           OR v_existing.outcome IS DISTINCT FROM v_outcome
           OR v_existing.selected_checkpoint IS DISTINCT FROM v_selected_checkpoint
           OR v_existing.reason IS DISTINCT FROM v_reason
           OR v_existing.liability_disposition
                IS DISTINCT FROM v_liability_disposition
           OR v_existing.effects_disposition
                IS DISTINCT FROM v_effects_disposition THEN
            RAISE EXCEPTION 'ride economic review request_id payload conflict';
        END IF;
        RETURN to_jsonb(v_existing) || jsonb_build_object('replayed', true);
    END IF;

    SELECT * INTO v_plan
    FROM public.ride_economic_plans
    WHERE ride_id = p_ride_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ride economic plan does not exist';
    END IF;

    -- The pre-lock lookup is only a fast replay path. A concurrent identical
    -- request may commit while this call waits for the plan row lock.
    SELECT * INTO v_existing
    FROM public.ride_economic_review_resolutions
    WHERE request_id = p_request_id;
    IF FOUND THEN
        IF v_existing.ride_id IS DISTINCT FROM p_ride_id
           OR v_existing.review_version IS DISTINCT FROM p_expected_review_version
           OR v_existing.actor_id IS DISTINCT FROM p_actor_id
           OR v_existing.outcome IS DISTINCT FROM v_outcome
           OR v_existing.selected_checkpoint IS DISTINCT FROM v_selected_checkpoint
           OR v_existing.reason IS DISTINCT FROM v_reason
           OR v_existing.liability_disposition
                IS DISTINCT FROM v_liability_disposition
           OR v_existing.effects_disposition
                IS DISTINCT FROM v_effects_disposition THEN
            RAISE EXCEPTION 'ride economic review request_id payload conflict';
        END IF;
        RETURN to_jsonb(v_existing) || jsonb_build_object('replayed', true);
    END IF;

    SELECT * INTO v_existing
    FROM public.ride_economic_review_resolutions
    WHERE ride_id = p_ride_id
      AND review_version = p_expected_review_version;
    IF FOUND THEN
        RAISE EXCEPTION 'ride economic review already resolved by request %',
            v_existing.request_id;
    END IF;
    IF v_plan.state <> 'review'
       OR v_plan.review_version <> p_expected_review_version THEN
        RAISE EXCEPTION 'ride economic review version fence failed';
    END IF;
    SELECT * INTO v_review
    FROM public.ride_economic_reviews
    WHERE ride_id = p_ride_id
      AND review_version = p_expected_review_version;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ride economic review audit record is missing';
    END IF;

    v_validation := public.validate_ride_economic_chain_evidence(
        p_ride_id,
        p_chain_evidence
    );
    v_verified_checkpoint := v_validation->>'checkpoint';
    v_attestation := p_chain_evidence->'attestation';
    v_cal := p_chain_evidence->'cal';

    IF v_outcome = 'reconcile' THEN
        IF v_selected_checkpoint IS NOT NULL THEN
            RAISE EXCEPTION 'reconcile derives its checkpoint from finalized chain evidence';
        END IF;
        v_result_state := v_verified_checkpoint;
    ELSIF v_outcome = 'resume' THEN
        IF v_selected_checkpoint IS NULL
           OR v_selected_checkpoint <> v_verified_checkpoint THEN
            RAISE EXCEPTION
                'resume checkpoint is not proven safe by finalized chain evidence';
        END IF;
        IF v_review.finalized_evidence #>> '{attestation,status}' = 'finalized'
           AND v_attestation->>'status' <> 'finalized' THEN
            RAISE EXCEPTION 'resume cannot discard previously finalized evidence';
        END IF;
        IF v_review.finalized_evidence #>> '{cal,status}' = 'finalized'
           AND v_cal->>'status' <> 'finalized' THEN
            RAISE EXCEPTION 'resume cannot discard previously finalized evidence';
        END IF;
        FOR v_prior_observation IN
            SELECT observation
            FROM jsonb_array_elements(
                v_review.finalized_evidence->'completions'
            ) observation
            WHERE observation->>'status' = 'finalized'
        LOOP
            IF NOT EXISTS (
                SELECT 1
                FROM jsonb_array_elements(
                    p_chain_evidence->'completions'
                ) observation
                WHERE observation->>'step_index'
                        = v_prior_observation->>'step_index'
                  AND observation->>'status' = 'finalized'
            ) THEN
                RAISE EXCEPTION 'resume cannot discard previously finalized evidence';
            END IF;
        END LOOP;
        v_result_state := v_selected_checkpoint;
    ELSE
        IF v_selected_checkpoint IS NOT NULL THEN
            RAISE EXCEPTION 'terminal rejection does not accept a resume checkpoint';
        END IF;
        IF v_liability_disposition IS NULL THEN
            RAISE EXCEPTION
                'terminal rejection requires an explicit liability disposition';
        END IF;
        IF v_effects_disposition IS NULL THEN
            RAISE EXCEPTION
                'terminal rejection requires an explicit effects disposition';
        END IF;
        v_result_state := 'rejected';
    END IF;

    IF v_outcome IN ('reconcile', 'resume') THEN
        FOR v_observation IN
            SELECT observation
            FROM jsonb_array_elements(
                p_chain_evidence->'completions'
            ) observation
        LOOP
            UPDATE public.ride_economic_completion_steps
            SET state = CASE v_observation->>'status'
                    WHEN 'finalized' THEN 'confirmed'
                    ELSE 'planned'
                END,
                actual_tx_signature = CASE v_observation->>'status'
                    WHEN 'finalized' THEN NULLIF(
                        v_observation->>'tx_signature', ''
                    )
                    ELSE NULL
                END,
                chain_confirmed_at = CASE v_observation->>'status'
                    WHEN 'finalized' THEN COALESCE(
                        NULLIF(v_observation->>'confirmed_at', '')::TIMESTAMPTZ,
                        (p_chain_evidence->>'verified_at')::TIMESTAMPTZ
                    )
                    ELSE NULL
                END,
                last_error = NULL,
                updated_at = now()
            WHERE ride_id = p_ride_id
              AND step_index = (v_observation->>'step_index')::INTEGER;
        END LOOP;

        UPDATE public.ride_economic_plans
        SET state = v_result_state,
            attestation_actual_tx_signature = CASE v_attestation->>'status'
                WHEN 'finalized' THEN NULLIF(
                    v_attestation->>'tx_signature', ''
                )
                ELSE NULL
            END,
            attestation_confirmed_at = CASE v_attestation->>'status'
                WHEN 'finalized' THEN COALESCE(
                    NULLIF(v_attestation->>'confirmed_at', '')::TIMESTAMPTZ,
                    (p_chain_evidence->>'verified_at')::TIMESTAMPTZ
                )
                ELSE NULL
            END,
            cal_actual_tx_signature = CASE v_cal->>'status'
                WHEN 'finalized' THEN NULLIF(v_cal->>'tx_signature', '')
                ELSE NULL
            END,
            cal_confirmed_at = CASE v_cal->>'status'
                WHEN 'finalized' THEN COALESCE(
                    NULLIF(v_cal->>'confirmed_at', '')::TIMESTAMPTZ,
                    (p_chain_evidence->>'verified_at')::TIMESTAMPTZ
                )
                ELSE NULL
            END,
            last_error = NULL,
            next_attempt_at = clock_timestamp(),
            lease_owner = NULL,
            lease_expires_at = NULL,
            lock_version = lock_version + 1,
            updated_at = now()
        WHERE ride_id = p_ride_id
          AND state = 'review'
          AND review_version = p_expected_review_version;
    ELSE
        UPDATE public.ride_economic_plans
        SET state = 'rejected',
            last_error = 'terminal_reject: ' || v_reason,
            lease_owner = NULL,
            lease_expires_at = NULL,
            lock_version = lock_version + 1,
            updated_at = now()
        WHERE ride_id = p_ride_id
          AND state = 'review'
          AND review_version = p_expected_review_version;
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ride economic review resolution CAS failed';
    END IF;

    INSERT INTO public.ride_economic_review_resolutions (
        request_id, ride_id, review_version, actor_id, outcome,
        selected_checkpoint, verified_checkpoint, result_state, reason,
        chain_evidence, liability_disposition, effects_disposition
    ) VALUES (
        p_request_id,
        p_ride_id,
        p_expected_review_version,
        p_actor_id,
        v_outcome,
        v_selected_checkpoint,
        v_verified_checkpoint,
        v_result_state,
        v_reason,
        p_chain_evidence,
        v_liability_disposition,
        v_effects_disposition
    ) RETURNING * INTO v_resolution;

    RETURN to_jsonb(v_resolution) || jsonb_build_object('replayed', false);
END;
$$;

