CREATE OR REPLACE FUNCTION public.validate_ride_economic_chain_evidence(
    p_ride_id UUID,
    p_chain_evidence JSONB
) RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_plan public.ride_economic_plans%ROWTYPE;
    v_step public.ride_economic_completion_steps%ROWTYPE;
    v_attestation JSONB;
    v_cal JSONB;
    v_observation JSONB;
    v_attestation_status TEXT;
    v_cal_status TEXT;
    v_completion_status TEXT;
    v_total_completions INTEGER;
    v_finalized_completions INTEGER := 0;
    v_match_count INTEGER;
    v_verified_at TIMESTAMPTZ;
    v_verified_checkpoint TEXT;
BEGIN
    SELECT * INTO v_plan
    FROM public.ride_economic_plans
    WHERE ride_id = p_ride_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ride economic plan does not exist';
    END IF;
    IF jsonb_typeof(p_chain_evidence) <> 'object'
       OR p_chain_evidence->>'version' <> '1'
       OR p_chain_evidence->>'commitment' <> 'finalized'
       OR COALESCE(btrim(p_chain_evidence->>'cluster'), '') = ''
       OR COALESCE(p_chain_evidence->>'finalized_slot', '') !~ '^[0-9]+$'
       OR (p_chain_evidence->>'finalized_slot')::NUMERIC <= 0 THEN
        RAISE EXCEPTION 'ride economic resolution requires finalized structured chain evidence';
    END IF;
    BEGIN
        v_verified_at := (p_chain_evidence->>'verified_at')::TIMESTAMPTZ;
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION 'ride economic chain evidence requires verified_at';
    END;
    IF v_verified_at IS NULL THEN
        RAISE EXCEPTION 'ride economic chain evidence requires verified_at';
    END IF;

    v_attestation := p_chain_evidence->'attestation';
    v_cal := p_chain_evidence->'cal';
    IF jsonb_typeof(v_attestation) <> 'object'
       OR jsonb_typeof(p_chain_evidence->'completions') <> 'array'
       OR jsonb_typeof(v_cal) <> 'object' THEN
        RAISE EXCEPTION 'ride economic chain evidence must cover every effect';
    END IF;

    v_attestation_status := v_attestation->>'status';
    IF v_attestation_status NOT IN ('absent', 'finalized')
       OR v_attestation->>'observed_slot'
            <> p_chain_evidence->>'finalized_slot'
       OR v_attestation->>'pda' <> v_plan.expected_attestation_pda
       OR lower(COALESCE(v_attestation->>'ride_hash_hex', ''))
            <> encode(v_plan.ride_hash, 'hex')
       OR lower(COALESCE(v_attestation->>'attestation_commitment_hex', ''))
            <> encode(v_plan.attestation_commitment, 'hex') THEN
        RAISE EXCEPTION 'attestation evidence conflicts with frozen plan facts';
    END IF;
    IF v_attestation_status = 'finalized' THEN
        IF COALESCE(v_attestation->>'account_data_hash_hex', '')
                !~ '^[0-9a-fA-F]{64}$'
           OR COALESCE(v_attestation->>'tx_signature', '') LIKE 'exists:%' THEN
            RAISE EXCEPTION 'finalized attestation evidence is incomplete';
        END IF;
    END IF;

    SELECT count(*)::INTEGER INTO v_total_completions
    FROM public.ride_economic_completion_steps
    WHERE ride_id = p_ride_id;
    IF jsonb_array_length(p_chain_evidence->'completions')
        <> v_total_completions THEN
        RAISE EXCEPTION 'completion evidence must cover every frozen step exactly once';
    END IF;

    FOR v_step IN
        SELECT * FROM public.ride_economic_completion_steps
        WHERE ride_id = p_ride_id
        ORDER BY step_index
    LOOP
        SELECT count(*)::INTEGER INTO v_match_count
        FROM jsonb_array_elements(p_chain_evidence->'completions') observation
        WHERE observation->>'step_index' = v_step.step_index::TEXT;
        IF v_match_count <> 1 THEN
            RAISE EXCEPTION 'completion evidence must cover every frozen step exactly once';
        END IF;
        SELECT observation INTO v_observation
        FROM jsonb_array_elements(p_chain_evidence->'completions') observation
        WHERE observation->>'step_index' = v_step.step_index::TEXT;

        v_completion_status := v_observation->>'status';
        IF v_completion_status NOT IN ('absent', 'finalized')
           OR v_observation->>'observed_slot'
                <> p_chain_evidence->>'finalized_slot'
           OR v_observation->>'pda' <> v_step.expected_receipt_pda
           OR public.require_ride_economic_uint(
                v_observation->'step_index', 'step_index', 2147483647
              ) <> v_step.step_index
           OR public.require_ride_economic_uint(
                v_observation->'vault_id', 'vault_id', 18446744073709551615
              ) <> v_step.vault_id
           OR public.require_ride_economic_uint(
                v_observation->'exact_tribute_base_units',
                'exact_tribute_base_units', 18446744073709551615
              ) <> v_step.exact_tribute_base_units
           OR lower(COALESCE(
                v_observation->>'completion_evidence_hash_hex', ''
              )) <> encode(v_step.completion_evidence_hash, 'hex') THEN
            RAISE EXCEPTION 'completion evidence conflicts with frozen step facts';
        END IF;
        IF v_completion_status = 'finalized' THEN
            IF COALESCE(v_observation->>'account_data_hash_hex', '')
                    !~ '^[0-9a-fA-F]{64}$'
               OR COALESCE(v_observation->>'tx_signature', '') LIKE 'exists:%' THEN
                RAISE EXCEPTION 'finalized completion evidence is incomplete';
            END IF;
            v_finalized_completions := v_finalized_completions + 1;
        END IF;
    END LOOP;

    v_cal_status := v_cal->>'status';
    IF v_cal_status NOT IN ('absent', 'finalized')
       OR v_cal->>'observed_slot' <> p_chain_evidence->>'finalized_slot'
       OR v_cal->>'pda' <> v_plan.expected_cal_receipt_pda
       OR lower(COALESCE(v_cal->>'ride_hash_hex', ''))
            <> encode(v_plan.ride_hash, 'hex')
       OR public.require_ride_economic_uint(
            v_cal->'amount_base_units',
            'amount_base_units',
            18446744073709551615
          ) <> v_plan.exact_cal_base_units THEN
        RAISE EXCEPTION 'CAL evidence conflicts with frozen plan facts';
    END IF;
    IF v_cal_status = 'finalized' THEN
        IF COALESCE(v_cal->>'account_data_hash_hex', '')
                !~ '^[0-9a-fA-F]{64}$'
           OR COALESCE(v_cal->>'tx_signature', '') LIKE 'exists:%' THEN
            RAISE EXCEPTION 'finalized CAL evidence is incomplete';
        END IF;
    END IF;

    IF v_attestation_status = 'absent'
       AND (v_finalized_completions > 0 OR v_cal_status = 'finalized') THEN
        RAISE EXCEPTION 'later effects cannot be finalized without attestation';
    END IF;
    IF v_cal_status = 'finalized'
       AND v_finalized_completions <> v_total_completions THEN
        RAISE EXCEPTION 'CAL cannot be finalized before every completion';
    END IF;

    v_verified_checkpoint := CASE
        WHEN v_attestation_status = 'absent' THEN 'planned'
        WHEN v_cal_status = 'finalized' THEN 'cal_confirmed'
        WHEN v_finalized_completions = v_total_completions
            THEN 'completions_confirmed'
        ELSE 'attestation_confirmed'
    END;
    RETURN jsonb_build_object(
        'checkpoint', v_verified_checkpoint,
        'finalized_completion_count', v_finalized_completions,
        'completion_count', v_total_completions,
        'verified_at', v_verified_at
    );
END;
$$;

