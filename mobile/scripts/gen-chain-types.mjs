#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../..');
const idlPath = path.join(repoRoot, 'protocol/anchor/idl/boulder_rollers.json');
const outPath = path.join(repoRoot, 'mobile/src/generated/boulderRollersIdl.ts');

const idl = JSON.parse(fs.readFileSync(idlPath, 'utf8'));
const accounts = (idl.accounts ?? []).map((item) => item.name).filter(Boolean).sort();
const instructions = (idl.instructions ?? []).map((item) => item.name).filter(Boolean).sort();

const generated =
  `// AUTO-GENERATED by mobile/scripts/gen-chain-types.mjs. Do not edit by hand.\n` +
    `// Source: protocol/anchor/idl/boulder_rollers.json\n\n` +
    `export const BOULDER_ROLLERS_IDL_NAME = 'boulder_rollers' as const;\n\n` +
    `export const BOULDER_ROLLERS_ACCOUNTS = ${JSON.stringify(accounts, null, 2)} as const;\n` +
    `export type BoulderRollersAccountName = typeof BOULDER_ROLLERS_ACCOUNTS[number];\n\n` +
    `export const BOULDER_ROLLERS_INSTRUCTIONS = ${JSON.stringify(instructions, null, 2)} as const;\n` +
    `export type BoulderRollersInstructionName = typeof BOULDER_ROLLERS_INSTRUCTIONS[number];\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outPath) || fs.readFileSync(outPath, 'utf8') !== generated) {
    console.error('Expo chain types are stale; run npm run gen:chain-types in mobile');
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(outPath), {recursive: true});
  fs.writeFileSync(outPath, generated);
}

console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${path.relative(repoRoot, outPath)} from ${path.relative(repoRoot, idlPath)}`);
