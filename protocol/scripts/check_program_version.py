#!/usr/bin/env python3
"""Bind the checked-in Anchor ABI to one monotonic ProgramConfig version."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, Optional, Tuple


REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST_RELATIVE = Path("protocol/program-version.json")
CANONICAL_IDL_RELATIVE = Path("protocol/anchor/idl/boulder_rollers.json")
IDL_MIRRORS = (
    Path("backend/idl/boulder_rollers.json"),
    Path("web/portal/public/idl/boulder_rollers.json"),
)
SNAPSHOT_DIRECTORY = Path("protocol/anchor/abi")
RUST_GENERATED = Path(
    "protocol/anchor/programs/boulder_rollers/src/generated_program_version.rs"
)
ANCHOR_TYPESCRIPT_GENERATED = Path("protocol/anchor/generated-program-version.ts")
BACKEND_GENERATED = Path("backend/app/generated_program_version.py")
INDEXER_GENERATED = Path("indexer/src/generated-program-version.ts")
MOBILE_GENERATED = Path("mobile/src/generated/boulderRollersProgramVersion.ts")
LIB_RS_RELATIVE = Path("protocol/anchor/programs/boulder_rollers/src/lib.rs")


class ProgramVersionError(RuntimeError):
    """The version ledger and checked-in ABI do not form one valid transition."""


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _strip_non_abi_fields(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            key: _strip_non_abi_fields(item)
            for key, item in sorted(value.items())
            if key not in {"docs", "msg", "metadata"}
        }
    if isinstance(value, list):
        return [_strip_non_abi_fields(item) for item in value]
    return value


def _sorted_named(items: Iterable[Dict[str, Any]]) -> list[Dict[str, Any]]:
    return sorted(items, key=lambda item: str(item.get("name", "")))


def abi_surface(idl: Dict[str, Any]) -> Dict[str, Any]:
    """Return the decoder and instruction compatibility surface of an Anchor IDL."""
    return _strip_non_abi_fields(
        {
            "name": idl.get("name"),
            "instructions": _sorted_named(idl.get("instructions", [])),
            "accounts": _sorted_named(idl.get("accounts", [])),
            "types": _sorted_named(idl.get("types", [])),
            "events": _sorted_named(idl.get("events", [])),
            "errors": sorted(idl.get("errors", []), key=lambda item: int(item["code"])),
        }
    )


def _canonical_json(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def abi_sha256(surface: Dict[str, Any]) -> str:
    return hashlib.sha256(_canonical_json(surface).encode("utf-8")).hexdigest()


def _snapshot_relative(version: int) -> Path:
    return SNAPSHOT_DIRECTORY / f"v0x{version:02x}.json"


def validate_version_transition(
    base_version: int,
    base_surface: Dict[str, Any],
    current_version: int,
    current_surface: Dict[str, Any],
) -> None:
    changed = base_surface != current_surface
    if changed and current_version == base_version:
        raise ProgramVersionError(
            "Anchor ABI changed but ProgramConfig version did not advance"
        )
    if changed and current_version != base_version + 1:
        raise ProgramVersionError(
            "Anchor ABI changes must advance ProgramConfig by exactly one version"
        )
    if not changed and current_version != base_version:
        raise ProgramVersionError(
            "ProgramConfig version advanced without a checked-in ABI change"
        )


def _render_rust(manifest: Dict[str, Any]) -> str:
    return (
        "// AUTO-GENERATED by protocol/scripts/check_program_version.py.\n"
        "// Source: protocol/program-version.json\n\n"
        f"pub const PREVIOUS_PROGRAM_VERSION: u8 = 0x{manifest['previous_version']:02X};\n"
        f"pub const CURRENT_PROGRAM_VERSION: u8 = 0x{manifest['current_version']:02X};\n"
        f"pub const PROGRAM_VERSION_FAMILY: &str = \"{manifest['family']}\";\n"
        "pub const PROGRAM_ABI_SHA256: &str =\n"
        f"    \"{manifest['abi_sha256']}\";\n"
    )


def _render_python(manifest: Dict[str, Any]) -> str:
    return (
        "# AUTO-GENERATED by protocol/scripts/check_program_version.py.\n"
        "# Source: protocol/program-version.json\n\n"
        f"PREVIOUS_PROGRAM_VERSION = 0x{manifest['previous_version']:02X}\n"
        f"CURRENT_PROGRAM_VERSION = 0x{manifest['current_version']:02X}\n"
        f"PROGRAM_VERSION_FAMILY = \"{manifest['family']}\"\n"
        f"PROGRAM_ABI_SHA256 = \"{manifest['abi_sha256']}\"\n"
    )


def _render_typescript(manifest: Dict[str, Any]) -> str:
    return (
        "// AUTO-GENERATED by protocol/scripts/check_program_version.py.\n"
        "// Source: protocol/program-version.json\n\n"
        f"export const PREVIOUS_PROGRAM_VERSION = 0x{manifest['previous_version']:02x} as const;\n"
        f"export const CURRENT_PROGRAM_VERSION = 0x{manifest['current_version']:02x} as const;\n"
        f"export const PROGRAM_VERSION_FAMILY = '{manifest['family']}' as const;\n"
        f"export const PROGRAM_ABI_SHA256 = '{manifest['abi_sha256']}' as const;\n"
    )


def _generated_outputs(manifest: Dict[str, Any]) -> Dict[Path, str]:
    typescript = _render_typescript(manifest)
    return {
        RUST_GENERATED: _render_rust(manifest),
        ANCHOR_TYPESCRIPT_GENERATED: typescript,
        BACKEND_GENERATED: _render_python(manifest),
        INDEXER_GENERATED: typescript,
        MOBILE_GENERATED: typescript,
    }


def _write_generated(root: Path, manifest: Dict[str, Any]) -> None:
    for relative_path, content in _generated_outputs(manifest).items():
        path = root / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def _validate_manifest(manifest: Dict[str, Any]) -> None:
    schema_version = manifest.get("schema_version")
    if schema_version not in {1, 2}:
        raise ProgramVersionError("unsupported program-version manifest schema")
    current = int(manifest["current_version"])
    previous = int(manifest["previous_version"])
    reserved = int(manifest["reserved_v4b_version"])
    if not 0 <= previous <= current <= 0xFF:
        raise ProgramVersionError("program versions must fit in u8 and be monotonic")
    if schema_version == 1:
        if manifest.get("family") != "V4-A":
            raise ProgramVersionError("schema 1 is reserved for the V4-A family")
        if current - previous not in {0, 1}:
            raise ProgramVersionError(
                "manifest previous version must equal or immediately precede current"
            )
        if current >= reserved:
            raise ProgramVersionError(
                "V4-A patch version consumed the reserved V4-B version"
            )
    else:
        bootstrap = manifest.get("family_bootstrap")
        if manifest.get("family") != "V4-B" or not isinstance(bootstrap, dict):
            raise ProgramVersionError(
                "schema 2 requires an explicit V4-B family bootstrap"
            )
        bootstrap_version = int(bootstrap.get("version", -1))
        predecessor_version = int(bootstrap.get("predecessor_version", -1))
        if (
            bootstrap.get("mode") != "fresh_program"
            or bootstrap.get("predecessor_family") != "V4-A"
            or bootstrap_version != reserved
            or not 0 <= predecessor_version < bootstrap_version
        ):
            raise ProgramVersionError("invalid V4-B fresh-program bootstrap declaration")
        if current < bootstrap_version:
            raise ProgramVersionError("V4-B version cannot precede its family bootstrap")
        if current == bootstrap_version:
            if previous != current:
                raise ProgramVersionError(
                    "fresh V4-B bootstrap must initialize previous and current at 0x4B"
                )
        elif current - previous != 1:
            raise ProgramVersionError(
                "post-bootstrap V4-B versions must advance exactly one patch"
            )
    expected_snapshot = _snapshot_relative(current).as_posix()
    if manifest.get("abi_snapshot") != expected_snapshot:
        raise ProgramVersionError(
            f"current ABI snapshot must be {expected_snapshot}"
        )


def check_repository(root: Path = REPO_ROOT) -> None:
    manifest_path = root / MANIFEST_RELATIVE
    if not manifest_path.exists():
        raise ProgramVersionError(f"missing {MANIFEST_RELATIVE}")
    manifest = _load_json(manifest_path)
    _validate_manifest(manifest)

    canonical_idl = _load_json(root / CANONICAL_IDL_RELATIVE)
    for mirror in IDL_MIRRORS:
        if _load_json(root / mirror) != canonical_idl:
            raise ProgramVersionError(f"IDL mirror drift: {mirror}")

    surface = abi_surface(canonical_idl)
    digest = abi_sha256(surface)
    snapshot_path = root / Path(manifest["abi_snapshot"])
    if not snapshot_path.exists():
        raise ProgramVersionError(f"missing ABI snapshot {manifest['abi_snapshot']}")
    if _load_json(snapshot_path) != surface:
        raise ProgramVersionError(
            "checked-in Anchor ABI differs from the current version snapshot"
        )
    if manifest.get("abi_sha256") != digest:
        raise ProgramVersionError(
            f"ABI digest mismatch: expected {manifest.get('abi_sha256')} got {digest}"
        )

    versions = []
    for path in sorted((root / SNAPSHOT_DIRECTORY).glob("v0x*.json")):
        match = re.fullmatch(r"v0x([0-9a-fA-F]{2})\.json", path.name)
        if not match:
            raise ProgramVersionError(f"invalid ABI snapshot name: {path.name}")
        versions.append(int(match.group(1), 16))
        if _canonical_json(_load_json(path)) != path.read_text(encoding="utf-8"):
            raise ProgramVersionError(f"ABI snapshot is not canonical JSON: {path}")
    if not versions or versions[-1] != int(manifest["current_version"]):
        raise ProgramVersionError("latest ABI snapshot is not the current version")
    if versions != sorted(set(versions)):
        raise ProgramVersionError("ABI snapshot versions are duplicated or unordered")

    for relative_path, expected in _generated_outputs(manifest).items():
        path = root / relative_path
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            raise ProgramVersionError(
                f"generated version expectation is stale: {relative_path}"
            )


def _git_show(root: Path, ref: str, relative_path: Path) -> Optional[str]:
    result = subprocess.run(
        ["git", "show", f"{ref}:{relative_path.as_posix()}"],
        cwd=root,
        text=True,
        capture_output=True,
        check=False,
    )
    return result.stdout if result.returncode == 0 else None


def _base_contract(root: Path, ref: str) -> Tuple[int, Dict[str, Any]]:
    idl_text = _git_show(root, ref, CANONICAL_IDL_RELATIVE)
    if idl_text is None:
        raise ProgramVersionError(f"base ref {ref} has no canonical Anchor IDL")
    manifest_text = _git_show(root, ref, MANIFEST_RELATIVE)
    if manifest_text is not None:
        version = int(json.loads(manifest_text)["current_version"])
    else:
        lib_text = _git_show(root, ref, LIB_RS_RELATIVE)
        match = re.search(
            r"PROGRAM_VERSION_[A-Z0-9_]+:\s*u8\s*=\s*(0x[0-9A-Fa-f]+|\d+)",
            lib_text or "",
        )
        if not match:
            raise ProgramVersionError(
                f"base ref {ref} has no readable ProgramConfig version"
            )
        version = int(match.group(1), 0)
    return version, abi_surface(json.loads(idl_text))


def validate_historical_snapshot(
    version: int,
    base_surface: Dict[str, Any],
    snapshot_surface: Dict[str, Any],
) -> None:
    if snapshot_surface != base_surface:
        raise ProgramVersionError(
            f"historical ABI snapshot v0x{version:02x} does not match the base ABI"
        )


def _is_fresh_family_bootstrap_transition(
    manifest: Dict[str, Any],
    base_manifest: Dict[str, Any],
    base_version: int,
) -> bool:
    bootstrap = manifest.get("family_bootstrap")
    is_bootstrap_declaration = (
        manifest.get("schema_version") == 2
        and isinstance(bootstrap, dict)
        and int(manifest["current_version"]) == int(bootstrap["version"])
    )
    if not is_bootstrap_declaration:
        return False
    if (
        base_manifest.get("family") == bootstrap["predecessor_family"]
        and base_version == int(bootstrap["predecessor_version"])
    ):
        return True
    if (
        base_manifest.get("family") == manifest["family"]
        and base_version == int(manifest["current_version"])
        and base_manifest.get("family_bootstrap") == bootstrap
    ):
        return False
    raise ProgramVersionError(
        "fresh V4-B bootstrap does not match the declared base family/version"
    )


def check_base_transition(root: Path, ref: str) -> None:
    manifest = _load_json(root / MANIFEST_RELATIVE)
    _validate_manifest(manifest)
    current_surface = abi_surface(_load_json(root / CANONICAL_IDL_RELATIVE))
    base_version, base_surface = _base_contract(root, ref)
    base_manifest_text = _git_show(root, ref, MANIFEST_RELATIVE)
    base_manifest = json.loads(base_manifest_text) if base_manifest_text else {}
    is_fresh_family_bootstrap = _is_fresh_family_bootstrap_transition(
        manifest,
        base_manifest,
        base_version,
    )
    if is_fresh_family_bootstrap:
        if current_surface == base_surface:
            raise ProgramVersionError(
                "fresh V4-B bootstrap requires a new checked-in Anchor ABI"
            )
    else:
        validate_version_transition(
            base_version,
            base_surface,
            int(manifest["current_version"]),
            current_surface,
        )

    base_snapshot_path = root / _snapshot_relative(base_version)
    if not base_snapshot_path.exists():
        raise ProgramVersionError(
            f"missing historical ABI snapshot for base version 0x{base_version:02x}"
        )
    validate_historical_snapshot(
        base_version,
        base_surface,
        _load_json(base_snapshot_path),
    )

    base_snapshot_listing = subprocess.run(
        ["git", "ls-tree", "-r", "--name-only", ref, SNAPSHOT_DIRECTORY.as_posix()],
        cwd=root,
        text=True,
        capture_output=True,
        check=False,
    )
    if base_snapshot_listing.returncode != 0:
        raise ProgramVersionError(f"cannot inspect ABI snapshots at base ref {ref}")
    for name in filter(None, base_snapshot_listing.stdout.splitlines()):
        relative = Path(name)
        base_content = _git_show(root, ref, relative)
        current_path = root / relative
        if base_content is None or not current_path.exists():
            raise ProgramVersionError(f"historical ABI snapshot was removed: {relative}")
        if current_path.read_text(encoding="utf-8") != base_content:
            raise ProgramVersionError(f"historical ABI snapshot was modified: {relative}")


def bootstrap(root: Path, version: int, family: str, reserved_v4b: int) -> None:
    manifest_path = root / MANIFEST_RELATIVE
    if manifest_path.exists():
        raise ProgramVersionError(f"{MANIFEST_RELATIVE} already exists")
    surface = abi_surface(_load_json(root / CANONICAL_IDL_RELATIVE))
    snapshot = _snapshot_relative(version)
    snapshot_path = root / snapshot
    snapshot_path.parent.mkdir(parents=True, exist_ok=True)
    snapshot_path.write_text(_canonical_json(surface), encoding="utf-8")
    manifest = {
        "schema_version": 1,
        "family": family,
        "previous_version": version,
        "current_version": version,
        "reserved_v4b_version": reserved_v4b,
        "abi_sha256": abi_sha256(surface),
        "abi_snapshot": snapshot.as_posix(),
    }
    manifest_path.write_text(_canonical_json(manifest), encoding="utf-8")
    _write_generated(root, manifest)


def advance(root: Path) -> None:
    manifest_path = root / MANIFEST_RELATIVE
    manifest = _load_json(manifest_path)
    _validate_manifest(manifest)
    current = int(manifest["current_version"])
    previous_surface = _load_json(root / Path(manifest["abi_snapshot"]))
    surface = abi_surface(_load_json(root / CANONICAL_IDL_RELATIVE))
    if surface == previous_surface:
        raise ProgramVersionError("cannot advance without a checked-in ABI change")
    next_version = current + 1
    if (
        manifest["family"] == "V4-A"
        and next_version >= int(manifest["reserved_v4b_version"])
    ):
        raise ProgramVersionError("no V4-A patch versions remain before reserved V4-B")
    snapshot = _snapshot_relative(next_version)
    snapshot_path = root / snapshot
    if snapshot_path.exists():
        raise ProgramVersionError(f"ABI snapshot already exists: {snapshot}")
    snapshot_path.write_text(_canonical_json(surface), encoding="utf-8")
    manifest.update(
        {
            "previous_version": current,
            "current_version": next_version,
            "abi_sha256": abi_sha256(surface),
            "abi_snapshot": snapshot.as_posix(),
        }
    )
    manifest_path.write_text(_canonical_json(manifest), encoding="utf-8")
    _write_generated(root, manifest)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--bootstrap", type=lambda value: int(value, 0))
    action.add_argument("--advance", action="store_true")
    action.add_argument("--write-generated", action="store_true")
    parser.add_argument("--family", default="V4-A")
    parser.add_argument("--reserved-v4b", type=lambda value: int(value, 0), default=0x4B)
    parser.add_argument("--base-ref")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        if args.bootstrap is not None:
            bootstrap(REPO_ROOT, args.bootstrap, args.family, args.reserved_v4b)
        elif args.advance:
            advance(REPO_ROOT)
        elif args.write_generated:
            _write_generated(REPO_ROOT, _load_json(REPO_ROOT / MANIFEST_RELATIVE))
        check_repository(REPO_ROOT)
        if args.base_ref:
            check_base_transition(REPO_ROOT, args.base_ref)
    except (OSError, KeyError, ValueError, ProgramVersionError) as error:
        print(f"program-version gate failed: {error}", file=sys.stderr)
        return 1
    manifest = _load_json(REPO_ROOT / MANIFEST_RELATIVE)
    print(
        "program-version gate passed: "
        f"{manifest['family']} 0x{manifest['current_version']:02X} "
        f"ABI {manifest['abi_sha256']}"
    )
    if args.advance or args.write_generated:
        print("generated version sources changed; rebuild the program binary before deployment")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
