#!/usr/bin/env python3
"""Install the rank-mark render output as typed portal assets.

The render output itself stays ignored. This exporter validates the numbered and podium
manifest contracts before replacing only its own ``src/assets/rankmarks``
directory with density-aware PNG imports and a typed lookup table.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import struct
import tempfile


EXPECTED_NUMBERED_RANKS = tuple(range(4, 51))
EXPECTED_PODIUM_RANKS = (1, 2, 3)
EXPECTED_SCALES = ("1x", "2x", "3x")
GENERATED_HEADER = "// Generated by tools/rankmarks/export_portal.py. Do not edit."

HERE = Path(__file__).resolve().parent
REPOSITORY_ROOT = HERE.parents[1]
DEFAULT_MANIFEST = HERE / "build" / "manifest.json"
DEFAULT_DESTINATION = (
    REPOSITORY_ROOT / "web" / "portal" / "src" / "assets" / "rankmarks"
)


class ExportError(ValueError):
    """The render output or destination does not satisfy the portal import contract."""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=DEFAULT_MANIFEST,
        help="Rank-mark manifest (default: tools/rankmarks/build/manifest.json).",
    )
    parser.add_argument(
        "--build-dir",
        type=Path,
        help="Sprite directory (default: the manifest's directory).",
    )
    parser.add_argument(
        "--destination",
        type=Path,
        default=DEFAULT_DESTINATION,
        help="Portal asset directory (default: web/portal/src/assets/rankmarks).",
    )
    return parser.parse_args()


def load_manifest(path: Path) -> dict:
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise ExportError(f"manifest is missing: {path}") from error
    except json.JSONDecodeError as error:
        raise ExportError(f"manifest is invalid JSON: {path}: {error}") from error

    if manifest.get("schema_version") != 2:
        raise ExportError("manifest schema_version must be 2")
    if not isinstance(manifest.get("codex"), dict):
        raise ExportError("manifest must carry the ratified tab codex block")
    if set(manifest.get("scales", {})) != set(EXPECTED_SCALES):
        raise ExportError("manifest must contain exactly scales 1x, 2x, and 3x")
    if manifest.get("rank_range") != {
        "min": 4,
        "max": 50,
        "order": "descending",
    }:
        raise ExportError("manifest numbered rank_range must be 4 through 50")

    ranks = manifest.get("ranks")
    if not isinstance(ranks, dict):
        raise ExportError("manifest ranks must be an object")
    if integer_keys(ranks, "manifest rank") != EXPECTED_NUMBERED_RANKS:
        raise ExportError("manifest must contain every numbered rank from 4 through 50")

    counts = manifest.get("counts", {})
    if counts.get("ranks") != len(EXPECTED_NUMBERED_RANKS):
        raise ExportError("manifest numbered rank count does not match the production set")
    expected_numbered_sprites = (
        len(EXPECTED_NUMBERED_RANKS) * len(EXPECTED_SCALES)
    )
    if counts.get("scale_sprites") != expected_numbered_sprites:
        raise ExportError("manifest numbered sprite count does not match the production set")

    podium = manifest.get("podium")
    if not isinstance(podium, dict):
        raise ExportError("manifest podium must be an object")
    if podium.get("corner_charge") is not False:
        raise ExportError("podium sprites must opt out of corner charge")
    if podium.get("rank_range") != {
        "min": 1,
        "max": 3,
        "order": "ascending",
    }:
        raise ExportError("manifest podium rank_range must be 1 through 3")
    if podium.get("scales") != manifest.get("scales"):
        raise ExportError("podium density scales must match numbered density scales")

    podium_ranks = podium.get("ranks")
    if not isinstance(podium_ranks, dict):
        raise ExportError("manifest podium ranks must be an object")
    if integer_keys(podium_ranks, "podium rank") != EXPECTED_PODIUM_RANKS:
        raise ExportError("manifest must contain podium ranks 1 through 3")

    podium_counts = podium.get("counts", {})
    if podium_counts.get("ranks") != len(EXPECTED_PODIUM_RANKS):
        raise ExportError("manifest podium rank count does not match the production set")
    if podium_counts.get("scale_sprites") != (
        len(EXPECTED_PODIUM_RANKS) * len(EXPECTED_SCALES)
    ):
        raise ExportError("manifest podium sprite count does not match the production set")

    return manifest


def integer_keys(value: dict, label: str) -> tuple[int, ...]:
    try:
        return tuple(sorted(int(key) for key in value))
    except (TypeError, ValueError) as error:
        raise ExportError(f"{label} keys must be integers") from error


def source_filename(value: object, context: str) -> str:
    if not isinstance(value, str) or Path(value).name != value:
        raise ExportError(f"unsafe sprite filename for {context}")
    return value


def validate_png(path: Path, expected_pixels: int) -> None:
    try:
        header = path.read_bytes()[:24]
    except FileNotFoundError as error:
        raise ExportError(
            f"missing rendered sprite: {path}\n"
            "Regenerate the sprites with /Applications/Blender.app/Contents/MacOS/Blender "
            "-b -P tools/rankmarks/render_production_assets.py, followed by the same command with "
            "-- --podium-only."
        ) from error

    if len(header) != 24 or header[:8] != b"\x89PNG\r\n\x1a\n":
        raise ExportError(f"rendered sprite is not a valid PNG: {path}")
    width, height = struct.unpack(">II", header[16:24])
    if (width, height) != (expected_pixels, expected_pixels):
        raise ExportError(
            f"rendered sprite has {width}x{height}px dimensions, expected "
            f"{expected_pixels}x{expected_pixels}px: {path}"
        )


def source_assets(
    manifest: dict,
    build_dir: Path,
) -> tuple[dict[str, Path], dict[int, tuple[str, str, str]]]:
    sources: dict[str, Path] = {}
    logical_assets: dict[int, tuple[str, str, str]] = {}
    scale_pixels = manifest["scales"]

    for rank in EXPECTED_NUMBERED_RANKS:
        files = manifest["ranks"][str(rank)].get("files", {})
        if not isinstance(files, dict):
            raise ExportError(f"rank {rank} files must be an object")

        names: list[str] = []
        for scale in EXPECTED_SCALES:
            name = source_filename(files.get(scale), f"rank {rank} {scale}")
            if name in sources:
                raise ExportError(f"duplicate numbered sprite filename: {name}")
            source = build_dir / name
            validate_png(source, scale_pixels[scale])
            sources[name] = source
            names.append(name)
        logical_assets[rank] = tuple(names)  # type: ignore[assignment]

    podium = manifest["podium"]
    for rank in EXPECTED_PODIUM_RANKS:
        files = podium["ranks"][str(rank)].get("files", {})
        if not isinstance(files, dict):
            raise ExportError(f"podium rank {rank} files must be an object")

        names = []
        for scale in EXPECTED_SCALES:
            name = source_filename(files.get(scale), f"podium rank {rank} {scale}")
            if name in sources:
                raise ExportError(f"duplicate podium sprite filename: {name}")
            source = build_dir / name
            validate_png(source, scale_pixels[scale])
            sources[name] = source
            names.append(name)
        logical_assets[rank] = tuple(names)  # type: ignore[assignment]

    if set(logical_assets) != set(range(1, 51)):
        raise ExportError("rank lookup does not cover all 50 production ranks")
    if len(sources) != 150:
        raise ExportError("physical sprite set must contain exactly 150 density PNGs")

    return sources, logical_assets


def typescript_index(
    sources: dict[str, Path],
    logical_assets: dict[int, tuple[str, str, str]],
) -> str:
    sorted_names = sorted(sources)
    imports = {
        name: f"asset{index:03d}"
        for index, name in enumerate(sorted_names)
    }
    lines = [GENERATED_HEADER, ""]
    lines.extend(
        f"import {imports[name]} from './{name}';"
        for name in sorted_names
    )
    lines.extend(
        [
            "",
            "export type RankMarkRank =",
        ]
    )
    rank_union = " | ".join(str(rank) for rank in range(1, 51))
    lines.append(f"  {rank_union};")
    lines.extend(
        [
            "export type RankMarkKey = `${RankMarkRank}`;",
            "",
            "export interface RankMarkAsset {",
            "  readonly src: string;",
            "  readonly srcSet: string;",
            "}",
            "",
            "function createRankMarkAsset(",
            "  oneX: string,",
            "  twoX: string,",
            "  threeX: string,",
            "): RankMarkAsset {",
            "  return {",
            "    src: oneX,",
            "    srcSet: `${oneX} 1x, ${twoX} 2x, ${threeX} 3x`,",
            "  };",
            "}",
            "",
            "export const rankMarkAssets = {",
        ]
    )
    for rank in range(1, 51):
        names = logical_assets[rank]
        variables = ", ".join(imports[name] for name in names)
        lines.append(f"  '{rank}': createRankMarkAsset({variables}),")
    lines.extend(
        [
            "} as const satisfies Readonly<Record<RankMarkKey, RankMarkAsset>>;",
            "",
            "export function resolveRankMarkAsset(",
            "  rank: number,",
            "): RankMarkAsset | null {",
            "  if (!Number.isInteger(rank) || rank < 1 || rank > 50) {",
            "    return null;",
            "  }",
            "",
            "  return rankMarkAssets[`${rank}` as RankMarkKey];",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def target_is_exporter_owned(target: Path) -> bool:
    if target.is_symlink():
        return False
    try:
        first_line = (target / "index.ts").read_text(encoding="utf-8").splitlines()[0]
    except (FileNotFoundError, IndexError, UnicodeDecodeError):
        return False
    return first_line == GENERATED_HEADER


def install_assets(
    destination: Path,
    sources: dict[str, Path],
    index_source: str,
) -> Path:
    if destination.is_symlink():
        raise ExportError(f"refusing to replace symlinked asset directory: {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and not target_is_exporter_owned(destination):
        raise ExportError(f"refusing to replace unowned asset directory: {destination}")

    staging = Path(
        tempfile.mkdtemp(prefix=f".{destination.name}-", dir=destination.parent)
    )
    try:
        for name, source in sources.items():
            shutil.copyfile(source, staging / name)
        (staging / "index.ts").write_text(index_source, encoding="utf-8")

        if destination.exists():
            shutil.rmtree(destination)
        staging.rename(destination)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
    return destination


def main() -> int:
    args = parse_args()
    manifest_path = args.manifest.resolve()
    build_dir = (args.build_dir or manifest_path.parent).resolve()

    try:
        requested_destination = args.destination.expanduser().absolute()
        if requested_destination.is_symlink():
            raise ExportError(
                f"refusing to replace symlinked asset directory: {requested_destination}"
            )
        destination = requested_destination.parent.resolve() / requested_destination.name
        manifest = load_manifest(manifest_path)
        sources, logical_assets = source_assets(manifest, build_dir)
        target = install_assets(
            destination,
            sources,
            typescript_index(sources, logical_assets),
        )
    except (ExportError, OSError) as error:
        raise SystemExit(f"export_portal.py: {error}") from error

    print(
        f"Installed {len(logical_assets)} rank entries "
        f"({len(sources)} PNGs) in {target}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
